"""
Reduced joint Bayesian recovery test for the Hybrid HGF.

Free parameters
---------------
1. value_tonic_volatility
2. shared_value_coupling
3. shared response noise SD

Fixed perceptual parameters
---------------------------
local_vol_tonic_volatility    = -6.0
local_volatility_coupling     = 0.7
shared_value_tonic_volatility = -4.0
local_vol_autoconnection      = 0.7
value_autoconnection          = 0.95

Known generating values
-----------------------
value_tonic_volatility = -7.824
shared_value_coupling  = 0.75
response_sd            = 0.10

Purpose
-------
The two Hybrid coupling strengths were individually recoverable but
showed substantial confounding when estimated together:

    local_volatility_coupling
    shared_value_coupling

Therefore local_volatility_coupling is fixed at 0.7 and this test asks
whether the architecture-relevant shared value coupling can be jointly
identified with value tonic volatility.

If successful, the proposed Hybrid fitting specification becomes:

    value_tonic_volatility
    shared_value_coupling
    response_sd

with the other perceptual parameters fixed.

Hybrid architecture
-------------------
input A <- value A <- local volatility A <- shared value
input B <- value B <- local volatility B <- shared value

Implementation detail
---------------------
The graph is constructed with static:

    shared_value_coupling = 0.75

The sampled JAX shared-value coupling is then inserted into the two
existing value-coupling edges before filtering.

Pointwise likelihoods are saved for later PSIS-LOO comparison.
"""

