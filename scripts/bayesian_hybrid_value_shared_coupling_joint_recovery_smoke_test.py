def save_outputs(
    *,
    output_dir: Path,
    idata,
    posterior_summary: pd.DataFrame,
    correlation_matrix: pd.DataFrame,
    diagnostics: dict,
    metadata: dict,
) -> None:
    """
    Save complete Hybrid recovery outputs.
    """

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    idata_path = (
        output_dir
        / "inference_data.nc"
    )

    summary_path = (
        output_dir
        / "posterior_summary.csv"
    )

    correlation_path = (
        output_dir
        / "posterior_correlation_matrix.csv"
    )

    diagnostics_path = (
        output_dir
        / "diagnostics.json"
    )

    metadata_path = (
        output_dir
        / "fit_metadata.json"
    )

    idata.to_netcdf(
        idata_path
    )

    posterior_summary.to_csv(
        summary_path
    )

    correlation_matrix.to_csv(
        correlation_path
    )

    with diagnostics_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            diagnostics,
            file,
            indent=2,
        )

    with metadata_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            metadata,
            file,
            indent=2,
        )

    print(
        f"\nSaved inference data: {idata_path}"
    )

    print(
        f"Saved posterior summary: {summary_path}"
    )

    print(
        f"Saved correlation matrix: {correlation_path}"
    )

    print(
        f"Saved diagnostics: {diagnostics_path}"
    )

    print(
        f"Saved metadata: {metadata_path}"
    )


