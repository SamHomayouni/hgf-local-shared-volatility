def set_hybrid_shared_value_coupling(
    model,
    shared_value_coupling,
):
    """
    Set one common shared-value coupling on both Hybrid edges:

        shared value (6) -> local volatility A (4)
        shared value (6) -> local volatility B (5)

    The graph topology remains fixed.
    """

    shared_value_coupling = (
        jnp.asarray(
            shared_value_coupling
        )
        .squeeze()
    )

    # -----------------------------------------------------------------
    # Shared parent -> local volatility A
    # -----------------------------------------------------------------

    set_coupling(
        attributes=model.attributes,
        edges=model.edges,
        parent_idx=SHARED_VALUE_NODE,
        child_idx=LOCAL_VOL_A_NODE,
        coupling=shared_value_coupling,
    )

    # -----------------------------------------------------------------
    # Shared parent -> local volatility B
    # -----------------------------------------------------------------

    set_coupling(
        attributes=model.attributes,
        edges=model.edges,
        parent_idx=SHARED_VALUE_NODE,
        child_idx=LOCAL_VOL_B_NODE,
        coupling=shared_value_coupling,
    )

    return model


# =====================================================================
# Dynamic Hybrid candidate
# =====================================================================

def build_dynamic_hybrid_model(
    *,
    value_tonic_volatility,
    shared_value_coupling,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
):
    """
    Build the proposed Hybrid candidate.

    Free
    ----
    value_tonic_volatility
    shared_value_coupling

    Fixed
    -----
    local_vol_tonic_volatility    = -6
    local_volatility_coupling     = 0.7
    shared_value_tonic_volatility = -4
    local_vol_autoconnection      = 0.7
    value_autoconnection          = 0.95
    """

    value_tonic_volatility = (
        jnp.asarray(
            value_tonic_volatility
        )
        .squeeze()
    )

    shared_value_coupling = (
        jnp.asarray(
            shared_value_coupling
        )
        .squeeze()
    )

    # -----------------------------------------------------------------
    # Construct static graph.
    #
    # value_tonic_volatility can enter node construction directly.
    #
    # shared_value_coupling is initially a normal Python float so that
    # the graph itself does not depend on a sampled JAX tracer.
    # -----------------------------------------------------------------

    model = build_shared_volatility_model(
        input_precision=(
            input_precision
        ),

        value_tonic_volatility=(
            value_tonic_volatility
        ),

        value_autoconnection_strength=(
            FIXED_VALUE_AUTOCONNECTION
        ),

        local_vol_tonic_volatility=(
            FIXED_LOCAL_VOL_TONIC_VOLATILITY
        ),

        local_volatility_coupling=(
            FIXED_LOCAL_VOLATILITY_COUPLING
        ),

        local_vol_autoconnection_strength=(
            FIXED_LOCAL_VOL_AUTOCONNECTION
        ),

        shared_value_tonic_volatility=(
            FIXED_SHARED_VALUE_TONIC_VOLATILITY
        ),

        # Static topology-construction value.
        shared_value_coupling=(
            TRUE_SHARED_VALUE_COUPLING
        ),

        update_type=(
            update_type
        ),

        max_posterior_precision=(
            max_posterior_precision
        ),
    )

    # -----------------------------------------------------------------
    # Replace static shared coupling with sampled coupling.
    # -----------------------------------------------------------------

    model = set_hybrid_shared_value_coupling(
        model,
        shared_value_coupling,
    )

    return model


# =====================================================================
# Likelihood functions
# =====================================================================

def create_likelihood_functions(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
):
    """
    Create scalar and pointwise JAX-compatible response likelihoods.
    """

    input_data_jax = jnp.asarray(
        input_data,
        dtype=jnp.float64,
    )

    responses_jax = jnp.asarray(
        responses,
        dtype=jnp.float64,
    )

    n_trials = int(
        len(responses)
    )

    include_mask = jnp.ones(
        n_trials,
        dtype=jnp.float64,
    )

    # -----------------------------------------------------------------
    # Trial zero corresponds to the initial HGF prior state.
    # -----------------------------------------------------------------

    include_mask = (
        include_mask
        .at[0]
        .set(0.0)
    )

    # =================================================================
    # Total likelihood for NUTS
    # =================================================================

    @wrap_jax
    def total_logp(
        value,
        value_tonic_volatility,
        log_shared_value_coupling,
        log_response_sd,
    ):
        """
        Return total response log probability.
        """

        value_tonic_volatility = (
            jnp.asarray(
                value_tonic_volatility
            )
            .squeeze()
        )

        log_shared_value_coupling = (
            jnp.asarray(
                log_shared_value_coupling
            )
            .squeeze()
        )

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        # -------------------------------------------------------------
        # Positive shared coupling.
        # -------------------------------------------------------------

        shared_value_coupling = jnp.exp(
            log_shared_value_coupling
        )

        # -------------------------------------------------------------
        # Build candidate HGF.
        # -------------------------------------------------------------

        model = build_dynamic_hybrid_model(
            value_tonic_volatility=(
                value_tonic_volatility
            ),

            shared_value_coupling=(
                shared_value_coupling
            ),

            input_precision=(
                input_precision
            ),

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        # -------------------------------------------------------------
        # Run HGF.
        # -------------------------------------------------------------

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = maybe_updated_model

        # -------------------------------------------------------------
        # Response-function inputs.
        # -------------------------------------------------------------

        response_inputs = (
            jnp.column_stack(
                [
                    value[:, 0],
                    value[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,

                response_function_inputs=(
                    response_inputs
                ),

                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        # Completely exclude trial zero.
        return -jnp.sum(
            surprise[1:]
        )

    # =================================================================
    # Pointwise likelihood for future PSIS-LOO
    # =================================================================

    @wrap_jax
    def pointwise_logp(
        value_tonic_volatility,
        log_shared_value_coupling,
        log_response_sd,
    ):
        """
        Return one joint A+B log likelihood per included trial.
        """

        value_tonic_volatility = (
            jnp.asarray(
                value_tonic_volatility
            )
            .squeeze()
        )

        log_shared_value_coupling = (
            jnp.asarray(
                log_shared_value_coupling
            )
            .squeeze()
        )

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        shared_value_coupling = jnp.exp(
            log_shared_value_coupling
        )

        model = build_dynamic_hybrid_model(
            value_tonic_volatility=(
                value_tonic_volatility
            ),

            shared_value_coupling=(
                shared_value_coupling
            ),

            input_precision=(
                input_precision
            ),

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = maybe_updated_model

        response_inputs = (
            jnp.column_stack(
                [
                    responses_jax[:, 0],
                    responses_jax[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,

                response_function_inputs=(
                    response_inputs
                ),

                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        return -surprise[1:]

    return (
        total_logp,
        pointwise_logp,
    )


# =====================================================================
# Bayesian fitting
# =====================================================================

def run_fit(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
    draws: int,
    tune: int,
    chains: int,
    cores: int,
    target_accept: float,
    random_seed: int,
):
    """
    Jointly estimate:

        value_tonic_volatility
        shared_value_coupling
        response_sd
    """

    (
        total_logp,
        pointwise_logp,
    ) = create_likelihood_functions(
        input_data=input_data,
        responses=responses,

        input_precision=(
            input_precision
        ),

        update_type=(
            update_type
        ),

        max_posterior_precision=(
            max_posterior_precision
        ),
    )

    with pm.Model() as model:

        # =============================================================
        # Value tonic volatility
        # =============================================================

        value_base = (
            pm.Normal.dist(
                mu=-3.0,
                sigma=5.0,
            )
        )

        value_tonic_volatility = (
            pm.Censored(
                "value_tonic_volatility",

                value_base,

                lower=-12.0,
                upper=2.0,

                initval=-7.0,
            )
        )

        # =============================================================
        # Shared value coupling
        #
        # Positive parameterization:
        #
        #     log(alpha) ~ Normal(0, 1)
        #     alpha      = exp(log(alpha))
        #
        # The prior median is 1.
        # The true generating value is 0.75.
        # =============================================================

        log_shared_value_coupling = (
            pm.Normal(
                "log_shared_value_coupling",

                mu=0.0,
                sigma=1.0,
            )
        )

        shared_value_coupling = (
            pm.Deterministic(
                "shared_value_coupling",

                pm.math.exp(
                    log_shared_value_coupling
                ),
            )
        )

        # =============================================================
        # Response noise
        # =============================================================

        log_response_sd = (
            pm.Normal(
                "log_response_sd",

                mu=np.log(
                    0.20
                ),

                sigma=1.0,
            )
        )

        response_sd = (
            pm.Deterministic(
                "response_sd",

                pm.math.exp(
                    log_response_sd
                ),
            )
        )

        # =============================================================
        # Response likelihood
        # =============================================================

        pm.CustomDist(
            "response_likelihood",

            value_tonic_volatility,
            log_shared_value_coupling,
            log_response_sd,

            logp=total_logp,

            observed=responses,
        )

        # =============================================================
        # Pointwise likelihood
        # =============================================================

        pm.Deterministic(
            "pointwise_loglikelihood",

            pointwise_logp(
                value_tonic_volatility,
                log_shared_value_coupling,
                log_response_sd,
            ),
        )

        # =============================================================
        # NUTS
        # =============================================================

        idata = pm.sample(
            draws=draws,
            tune=tune,

            chains=chains,
            cores=cores,

            backend="jax",

            target_accept=(
                target_accept
            ),

            random_seed=(
                random_seed
            ),

            return_inferencedata=True,
        )

    # -----------------------------------------------------------------
    # Standard ArviZ pointwise likelihood group.
    # -----------------------------------------------------------------

    idata[
        "log_likelihood"
    ] = (
        idata.posterior[
            "pointwise_loglikelihood"
        ]
        .to_dataset(
            name="log_likelihood"
        )
    )

    return (
        model,
        idata,
    )


# =====================================================================
# Posterior helpers
# =====================================================================

def flatten_samples(
    idata,
    variable_name: str,
) -> np.ndarray:
    """
    Flatten chain and draw dimensions.
    """

    return (
        idata.posterior[
            variable_name
        ]
        .values
        .reshape(-1)
    )


def make_correlation_matrix(
    idata,
) -> pd.DataFrame:
    """
    Posterior correlation matrix on interpretable parameter scales.
    """

    samples = pd.DataFrame(
        {
            "value_tonic_volatility": (
                flatten_samples(
                    idata,
                    "value_tonic_volatility",
                )
            ),

            "shared_value_coupling": (
                flatten_samples(
                    idata,
                    "shared_value_coupling",
                )
            ),

            "response_sd": (
                flatten_samples(
                    idata,
                    "response_sd",
                )
            ),
        }
    )

    return samples.corr()


# =====================================================================
# Recovery diagnostics
