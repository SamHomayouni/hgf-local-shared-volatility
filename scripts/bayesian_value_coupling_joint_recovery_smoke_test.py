def set_volatility_edge_coupling(
    model,
    *,
    parent_idx: int,
    child_idx: int,
    coupling,
):
    """
    Replace the numerical coupling strength of one existing
    volatility edge without modifying network topology.

    pyHGF stores coupling strengths on both sides:

        child:
            volatility_coupling_parents

        parent:
            volatility_coupling_children
    """

    coupling = (
        jnp.asarray(
            coupling
        )
        .squeeze()
    )

    # -----------------------------------------------------------------
    # Find the parent in the child's edge definition.
    # -----------------------------------------------------------------

    volatility_parents = (
        model.edges[
            child_idx
        ].volatility_parents
    )

    if volatility_parents is None:
        raise ValueError(
            f"Node {child_idx} has no volatility parents."
        )

    try:
        parent_position = (
            volatility_parents.index(
                parent_idx
            )
        )

    except ValueError as error:
        raise ValueError(
            f"Node {parent_idx} is not a volatility parent "
            f"of node {child_idx}."
        ) from error

    # -----------------------------------------------------------------
    # Find child position on parent side.
    # -----------------------------------------------------------------

    volatility_children = (
        model.edges[
            parent_idx
        ].volatility_children
    )

    if volatility_children is None:
        raise ValueError(
            f"Node {parent_idx} has no volatility children."
        )

    try:
        child_position = (
            volatility_children.index(
                child_idx
            )
        )

    except ValueError as error:
        raise ValueError(
            f"Node {child_idx} is not a volatility child "
            f"of node {parent_idx}."
        ) from error

    # -----------------------------------------------------------------
    # Child-side representation.
    # -----------------------------------------------------------------

    child_couplings = (
        model.attributes[
            child_idx
        ][
            "volatility_coupling_parents"
        ]
    )

    model.attributes[
        child_idx
    ][
        "volatility_coupling_parents"
    ] = (
        child_couplings
        .at[
            parent_position
        ]
        .set(
            coupling
        )
    )

    # -----------------------------------------------------------------
    # Parent-side representation.
    # -----------------------------------------------------------------

    parent_couplings = (
        model.attributes[
            parent_idx
        ][
            "volatility_coupling_children"
        ]
    )

    model.attributes[
        parent_idx
    ][
        "volatility_coupling_children"
    ] = (
        parent_couplings
        .at[
            child_position
        ]
        .set(
            coupling
        )
    )

    return model


def set_local_volatility_coupling(
    model,
    volatility_coupling,
):
    """
    Apply one shared coupling strength to the two Local-model edges:

        volatility A -> value A
        volatility B -> value B
    """

    model = set_volatility_edge_coupling(
        model,
        parent_idx=VOLATILITY_A_NODE,
        child_idx=VALUE_A_NODE,
        coupling=volatility_coupling,
    )

    model = set_volatility_edge_coupling(
        model,
        parent_idx=VOLATILITY_B_NODE,
        child_idx=VALUE_B_NODE,
        coupling=volatility_coupling,
    )

    return model


