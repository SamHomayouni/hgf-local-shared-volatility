"""
Reduced joint Bayesian recovery test for the Local-only HGF.

Free parameters
---------------
1. value_tonic_volatility
2. volatility_coupling
3. shared response noise SD

Fixed perceptual parameter
--------------------------
volatility_tonic_volatility = -6.0

Known generating values
-----------------------
value_tonic_volatility = -7.824
volatility_coupling    = 1.0
response_sd            = 0.10

Purpose
-------
The previous full Local fit showed strong posterior dependence among:

    value_tonic_volatility
    volatility_tonic_volatility
    volatility_coupling

This reduced test removes volatility_tonic_volatility from the fitted
parameter set and asks whether value tonic volatility and volatility
coupling can be identified jointly.

Important implementation detail
--------------------------------
The network topology is created using static:

    volatility_coupling = 1.0

The sampled JAX coupling is inserted into the already-created edge
attributes before the HGF is run.
"""

