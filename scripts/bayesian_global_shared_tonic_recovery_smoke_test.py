"""
Bayesian parameter-recovery smoke test for the Global-only HGF.

Free parameters
---------------
1. shared_volatility_tonic_volatility
2. shared response noise SD

Fixed perceptual parameters
---------------------------
value_tonic_volatility       = -7.824
shared_volatility_coupling   = 1.0

Known generating values
-----------------------
shared_volatility_tonic_volatility = -6.0
response_sd                        = 0.10

Purpose
-------
This is the first parameter-recovery test for the Global-only architecture.

It asks whether the tonic volatility of the single shared volatility
state can be inferred from synthetic continuous prediction behavior
when the remaining perceptual parameters are fixed.

The model is fitted using the same:

    pyHGF
        -> JAX
        -> PyTensor wrap_jax
        -> PyMC / NUTS

pipeline already validated for the Local-only model.

Trial 0 is excluded from the response likelihood.

Pointwise log likelihoods are retained for later PSIS-LOO model
comparison.
"""

