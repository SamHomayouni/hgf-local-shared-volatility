def load_model_input(
    environment_dir: Path,
) -> np.ndarray:
    """
    Load the two-stream environmental observations.
    """

    input_path = (
        environment_dir
        / "model_runs"
        / "model_input_data.npy"
    )

    if not input_path.exists():
        raise FileNotFoundError(
            f"Could not find model input data: {input_path}"
        )

    input_data = np.load(
        input_path
    )

    if input_data.ndim != 2:
        raise ValueError(
            f"Expected 2D model input, got {input_data.shape}."
        )

    if input_data.shape[1] != 2:
        raise ValueError(
            f"Expected two streams, got {input_data.shape}."
        )

    if not np.isfinite(
        input_data
    ).all():
        raise ValueError(
            "Model input contains non-finite values."
        )

    return input_data.astype(
        float
    )


def load_synthetic_responses(
    *,
    environment_dir: Path,
) -> tuple[np.ndarray, dict]:
    """
    Load responses generated by the Global-only perceptual model.
    """

    response_dir = (
        environment_dir
        / "synthetic_responses"
        / "global_only"
    )

    response_path = (
        response_dir
        / "synthetic_continuous_predictions.csv"
    )

    metadata_path = (
        response_dir
        / "response_model_metadata.json"
    )

    if not response_path.exists():
        raise FileNotFoundError(
            f"Could not find synthetic responses: {response_path}"
        )

    if not metadata_path.exists():
        raise FileNotFoundError(
            f"Could not find response metadata: {metadata_path}"
        )

    response_df = pd.read_csv(
        response_path
    )

    with metadata_path.open(
        "r",
        encoding="utf-8",
    ) as file:
        metadata = json.load(
            file
        )

    required_columns = {
        "participant_prediction_A",
        "participant_prediction_B",
    }

    missing_columns = (
        required_columns
        - set(response_df.columns)
    )

    if missing_columns:
        raise ValueError(
            "Synthetic response file is missing columns: "
            f"{sorted(missing_columns)}"
        )

    generating_model = metadata.get(
        "generating_perceptual_model"
    )

    if generating_model != "global_only":
        raise ValueError(
            "This test requires behavior generated by "
            f"global_only, but metadata reports {generating_model!r}."
        )

    responses = response_df[
        [
            "participant_prediction_A",
            "participant_prediction_B",
        ]
    ].to_numpy(
        dtype=float
    )

    if not np.isfinite(
        responses
    ).all():
        raise ValueError(
            "Synthetic responses contain non-finite values."
        )

    return (
        responses,
        metadata,
    )


# =====================================================================
# Likelihood functions
# =====================================================================

def create_likelihood_functions(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
):
    """
    Create total and pointwise JAX-compatible likelihoods.

    Free perceptual parameter
    -------------------------
    shared_volatility_tonic_volatility

    Free response parameter
    -----------------------
    log_response_sd

    Fixed
    -----
    value_tonic_volatility     = -7.824
    shared_volatility_coupling = 1.0
    """

    input_data_jax = jnp.asarray(
        input_data,
        dtype=jnp.float64,
    )

    responses_jax = jnp.asarray(
        responses,
        dtype=jnp.float64,
    )

    n_trials = int(
        len(responses)
    )

    include_mask = jnp.ones(
        n_trials,
        dtype=jnp.float64,
    )

    # Trial 0 corresponds to the network's initial prior state.
    include_mask = (
        include_mask
        .at[0]
        .set(0.0)
    )

    # =================================================================
    # Total likelihood used by NUTS
    # =================================================================

    @wrap_jax
    def total_logp(
        value,
        shared_volatility_tonic_volatility,
        log_response_sd,
    ):
        """
        Scalar total response log probability.
        """

        shared_volatility_tonic_volatility = (
            jnp.asarray(
                shared_volatility_tonic_volatility
            )
            .squeeze()
        )

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        model = build_global_only_model(
            input_precision=(
                input_precision
            ),

            value_tonic_volatility=(
                FIXED_VALUE_TONIC_VOLATILITY
            ),

            shared_volatility_tonic_volatility=(
                shared_volatility_tonic_volatility
            ),

            shared_volatility_coupling=(
                FIXED_SHARED_VOLATILITY_COUPLING
            ),

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = (
                maybe_updated_model
            )

        response_inputs = (
            jnp.column_stack(
                [
                    value[:, 0],
                    value[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,

                response_function_inputs=(
                    response_inputs
                ),

                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        return -jnp.sum(
            surprise[1:]
        )

    # =================================================================
    # Pointwise likelihood for later PSIS-LOO
    # =================================================================

    @wrap_jax
    def pointwise_logp(
        shared_volatility_tonic_volatility,
        log_response_sd,
    ):
        """
        Return one joint A+B log probability per included trial.
        """

        shared_volatility_tonic_volatility = (
            jnp.asarray(
                shared_volatility_tonic_volatility
            )
            .squeeze()
        )

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        model = build_global_only_model(
            input_precision=(
                input_precision
            ),

            value_tonic_volatility=(
                FIXED_VALUE_TONIC_VOLATILITY
            ),

            shared_volatility_tonic_volatility=(
                shared_volatility_tonic_volatility
            ),

            shared_volatility_coupling=(
                FIXED_SHARED_VOLATILITY_COUPLING
            ),

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = (
                maybe_updated_model
            )

        response_inputs = (
            jnp.column_stack(
                [
                    responses_jax[:, 0],
                    responses_jax[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,

                response_function_inputs=(
                    response_inputs
                ),

                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        return -surprise[1:]

    return (
        total_logp,
        pointwise_logp,
    )


# =====================================================================
# Bayesian fitting
# =====================================================================

def run_fit(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
    draws: int,
    tune: int,
    chains: int,
    cores: int,
    target_accept: float,
    random_seed: int,
):
    """
    Estimate shared volatility tonic volatility and response SD.
    """

    (
        total_logp,
        pointwise_logp,
    ) = create_likelihood_functions(
        input_data=input_data,
        responses=responses,

        input_precision=(
            input_precision
        ),

        update_type=(
            update_type
        ),

        max_posterior_precision=(
            max_posterior_precision
        ),
    )

    with pm.Model() as model:

        # =================================================================
        # Shared-volatility tonic volatility
        # =================================================================

        shared_volatility_base = (
            pm.Normal.dist(
                mu=-3.0,
                sigma=5.0,
            )
        )

        shared_volatility_tonic_volatility = (
            pm.Censored(
                "shared_volatility_tonic_volatility",

                shared_volatility_base,

                lower=-12.0,
                upper=2.0,

                initval=-5.0,
            )
        )

        # =================================================================
        # Response noise
        # =================================================================

        log_response_sd = pm.Normal(
            "log_response_sd",

            mu=np.log(
                0.20
            ),

            sigma=1.0,
        )

        response_sd = pm.Deterministic(
            "response_sd",

            pm.math.exp(
                log_response_sd
            ),
        )

        # =================================================================
        # Response likelihood
        # =================================================================

        pm.CustomDist(
            "response_likelihood",

            shared_volatility_tonic_volatility,
            log_response_sd,

            logp=total_logp,

            observed=responses,
        )

        # =================================================================
        # Pointwise likelihood
        # =================================================================

        pm.Deterministic(
            "pointwise_loglikelihood",

            pointwise_logp(
                shared_volatility_tonic_volatility,
                log_response_sd,
            ),
        )

        # =================================================================
        # NUTS
        # =================================================================

        idata = pm.sample(
            draws=draws,
            tune=tune,

            chains=chains,
            cores=cores,

            backend="jax",

            target_accept=(
                target_accept
            ),

            random_seed=(
                random_seed
            ),

            return_inferencedata=True,
        )

    # -----------------------------------------------------------------
    # Add pointwise log likelihood in the standard ArviZ group.
    # -----------------------------------------------------------------

    idata[
        "log_likelihood"
    ] = (
        idata.posterior[
            "pointwise_loglikelihood"
        ]
        .to_dataset(
            name="log_likelihood"
        )
    )

    return (
        model,
        idata,
    )


# =====================================================================
# Posterior helpers
# =====================================================================

def flatten_samples(
    idata,
    variable_name: str,
) -> np.ndarray:
    """
    Flatten chain and draw dimensions.
    """

    return (
        idata.posterior[
            variable_name
        ]
        .values
        .reshape(-1)
    )


