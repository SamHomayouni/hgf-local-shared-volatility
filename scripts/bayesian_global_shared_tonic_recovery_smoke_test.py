def summarize_recovery(
    *,
    idata,
    true_response_sd: float,
) -> tuple[
    pd.DataFrame,
    dict,
]:
    """
    Summarize recovery and sampler diagnostics.
    """

    posterior_summary = az.summary(
        idata,

        var_names=[
            "shared_volatility_tonic_volatility",
            "log_response_sd",
            "response_sd",
        ],

        round_to=4,
    )

    # -----------------------------------------------------------------
    # Posterior samples
    # -----------------------------------------------------------------

    shared_volatility_samples = (
        flatten_samples(
            idata,
            "shared_volatility_tonic_volatility",
        )
    )

    response_sd_samples = (
        flatten_samples(
            idata,
            "response_sd",
        )
    )

    # -----------------------------------------------------------------
    # HDIs
    # -----------------------------------------------------------------

    shared_volatility_hdi = az.hdi(
        shared_volatility_samples,
        hdi_prob=0.94,
    )

    response_sd_hdi = az.hdi(
        response_sd_samples,
        hdi_prob=0.94,
    )

    # -----------------------------------------------------------------
    # Posterior correlation
    # -----------------------------------------------------------------

    shared_volatility_vs_response_sd = float(
        np.corrcoef(
            shared_volatility_samples,
            response_sd_samples,
        )[0, 1]
    )

    # -----------------------------------------------------------------
    # Sampling diagnostics
    # -----------------------------------------------------------------

    n_divergences = int(
        idata.sample_stats[
            "diverging"
        ]
        .sum()
        .values
    )

    maximum_r_hat = float(
        posterior_summary[
            "r_hat"
        ].max()
    )

    minimum_ess_bulk = float(
        posterior_summary[
            "ess_bulk"
        ].min()
    )

    minimum_ess_tail = float(
        posterior_summary[
            "ess_tail"
        ].min()
    )

    diagnostics = {

        # =============================================================
        # Fixed parameters
        # =============================================================

        "fixed_value_tonic_volatility": float(
            FIXED_VALUE_TONIC_VOLATILITY
        ),

        "fixed_shared_volatility_coupling": float(
            FIXED_SHARED_VOLATILITY_COUPLING
        ),

        # =============================================================
        # Shared-volatility tonic volatility
        # =============================================================

        "true_shared_volatility_tonic_volatility": float(
            TRUE_SHARED_VOLATILITY_TONIC_VOLATILITY
        ),

        "posterior_mean_shared_volatility_tonic_volatility": float(
            np.mean(
                shared_volatility_samples
            )
        ),

        "posterior_median_shared_volatility_tonic_volatility": float(
            np.median(
                shared_volatility_samples
            )
        ),

        "shared_volatility_tonic_volatility_hdi_94_lower": float(
            shared_volatility_hdi[0]
        ),

        "shared_volatility_tonic_volatility_hdi_94_upper": float(
            shared_volatility_hdi[1]
        ),

        "true_shared_volatility_tonic_volatility_inside_94_hdi": bool(
            shared_volatility_hdi[0]
            <= TRUE_SHARED_VOLATILITY_TONIC_VOLATILITY
            <= shared_volatility_hdi[1]
        ),

        # =============================================================
        # Response SD
        # =============================================================

        "true_response_sd": float(
            true_response_sd
        ),

        "posterior_mean_response_sd": float(
            np.mean(
                response_sd_samples
            )
        ),

        "posterior_median_response_sd": float(
            np.median(
                response_sd_samples
            )
        ),

        "response_sd_hdi_94_lower": float(
            response_sd_hdi[0]
        ),

        "response_sd_hdi_94_upper": float(
            response_sd_hdi[1]
        ),

        "true_response_sd_inside_94_hdi": bool(
            response_sd_hdi[0]
            <= true_response_sd
            <= response_sd_hdi[1]
        ),

        # =============================================================
        # Posterior dependence
        # =============================================================

        "posterior_correlation_shared_volatility_tonic_vs_response_sd": (
            shared_volatility_vs_response_sd
        ),

        "absolute_correlation_shared_volatility_tonic_vs_response_sd": float(
            abs(
                shared_volatility_vs_response_sd
            )
        ),

        # =============================================================
        # Sampling
        # =============================================================

        "n_divergences": int(
            n_divergences
        ),

        "maximum_r_hat": float(
            maximum_r_hat
        ),

        "minimum_ess_bulk": float(
            minimum_ess_bulk
        ),

        "minimum_ess_tail": float(
            minimum_ess_tail
        ),
    }

    return (
        posterior_summary,
        diagnostics,
    )


