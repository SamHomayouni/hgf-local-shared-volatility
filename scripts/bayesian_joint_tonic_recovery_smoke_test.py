def build_arg_parser() -> argparse.ArgumentParser:
    """
    Build command-line interface.
    """

    parser = argparse.ArgumentParser(
        description=(
            "Jointly recover value tonic volatility, "
            "volatility-state tonic volatility, and response noise."
        )
    )

    parser.add_argument(
        "--environment-dir",
        type=str,
        required=True,
    )

    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
    )

    parser.add_argument(
        "--input-precision",
        type=float,
        default=100.0,
    )

    parser.add_argument(
        "--update-type",
        type=str,
        default="eHGF",
        choices=[
            "eHGF",
            "standard",
            "unbounded",
        ],
    )

    parser.add_argument(
        "--max-posterior-precision",
        type=float,
        default=1e10,
    )

    parser.add_argument(
        "--draws",
        type=int,
        default=1000,
    )

    parser.add_argument(
        "--tune",
        type=int,
        default=1000,
    )

    # We use four chains now because this is the first test where
    # posterior dependence between perceptual parameters matters.
    parser.add_argument(
        "--chains",
        type=int,
        default=4,
    )

    parser.add_argument(
        "--cores",
        type=int,
        default=1,
    )

    parser.add_argument(
        "--target-accept",
        type=float,
        default=0.95,
    )

    parser.add_argument(
        "--random-seed",
        type=int,
        default=2026,
    )

    return parser


# ---------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------

def main() -> None:
    """
    Run the joint tonic-volatility recovery test.
    """

    args = (
        build_arg_parser()
        .parse_args()
    )

    environment_dir = Path(
        args.environment_dir
    )

    if args.output_dir is None:

        output_dir = (
            environment_dir
            / "model_recovery"
            / "bayesian_parameter_smoke_test"
            / "joint_tonic_volatilities"
        )

    else:

        output_dir = Path(
            args.output_dir
        )

    print(
        "\n========================================"
    )

    print(
        "Joint Bayesian tonic-volatility recovery"
    )

    print(
        "========================================"
    )

    print(
        f"Environment: "
        f"{environment_dir}"
    )

    print(
        "Generating model: local_only"
    )

    print(
        "Candidate model: local_only"
    )

    print(
        f"True value tonic volatility: "
        f"{TRUE_VALUE_TONIC_VOLATILITY}"
    )

    print(
        f"True volatility tonic volatility: "
        f"{TRUE_VOLATILITY_TONIC_VOLATILITY}"
    )

    # -------------------------------------------------------------
    # Load data
    # -------------------------------------------------------------

    input_data = load_model_input(
        environment_dir
    )

    (
        responses,
        response_metadata,
    ) = load_synthetic_responses(
        environment_dir=environment_dir,
    )

    if len(input_data) != len(responses):
        raise ValueError(
            "Number of input trials and response trials "
            "does not match."
        )

    true_response_sd_A = float(
        response_metadata[
            "response_sd_A"
        ]
    )

    true_response_sd_B = float(
        response_metadata[
            "response_sd_B"
        ]
    )

    if not np.isclose(
        true_response_sd_A,
        true_response_sd_B,
    ):
        raise ValueError(
            "This recovery test assumes shared response noise."
        )

    true_response_sd = (
        true_response_sd_A
    )

    print(
        f"True response SD: "
        f"{true_response_sd}"
    )

    print(
        f"Trials total: "
        f"{len(responses)}"
    )

    print(
        f"Trials in likelihood: "
        f"{len(responses) - 1}"
    )

    print(
        f"Chains: {args.chains}"
    )

    print(
        f"Draws per chain: "
        f"{args.draws}"
    )

    print(
        f"Tuning steps per chain: "
        f"{args.tune}"
    )

    # -------------------------------------------------------------
    # Fit
    # -------------------------------------------------------------

    _, idata = run_fit(
        input_data=input_data,
        responses=responses,
        input_precision=(
            args.input_precision
        ),
        update_type=(
            args.update_type
        ),
        max_posterior_precision=(
            args.max_posterior_precision
        ),
        draws=args.draws,
        tune=args.tune,
        chains=args.chains,
        cores=args.cores,
        target_accept=(
            args.target_accept
        ),
        random_seed=(
            args.random_seed
        ),
    )

    # -------------------------------------------------------------
