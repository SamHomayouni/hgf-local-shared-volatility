def save_outputs(
    *,
    output_dir: Path,
    idata,
    posterior_summary: pd.DataFrame,
    diagnostics: dict,
    metadata: dict,
) -> None:
    """
    Save all joint-recovery outputs.
    """

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    idata_path = (
        output_dir
        / "inference_data.nc"
    )

    posterior_summary_path = (
        output_dir
        / "posterior_summary.csv"
    )

    diagnostics_path = (
        output_dir
        / "diagnostics.json"
    )

    metadata_path = (
        output_dir
        / "fit_metadata.json"
    )

    idata.to_netcdf(
        idata_path
    )

    posterior_summary.to_csv(
        posterior_summary_path
    )

    with diagnostics_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            diagnostics,
            file,
            indent=2,
        )

    with metadata_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            metadata,
            file,
            indent=2,
        )

    print(
        f"\nSaved inference data: "
        f"{idata_path}"
    )

    print(
        f"Saved posterior summary: "
        f"{posterior_summary_path}"
    )

    print(
        f"Saved diagnostics: "
        f"{diagnostics_path}"
    )

    print(
        f"Saved metadata: "
        f"{metadata_path}"
    )


