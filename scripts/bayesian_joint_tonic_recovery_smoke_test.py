"""
Joint Bayesian recovery of the two local-only tonic-volatility parameters.

Free parameters
---------------
1. value_tonic_volatility
2. volatility_tonic_volatility
3. shared response noise SD

Known generating values
-----------------------
value_tonic_volatility      = -7.824
volatility_tonic_volatility = -6.0
response_sd                 = 0.10

Purpose
-------
The two tonic-volatility parameters have already been tested separately.

This script now asks whether they remain identifiable when estimated
simultaneously.

The most important new diagnostic is the posterior correlation between:

    value_tonic_volatility

and

    volatility_tonic_volatility

A strong posterior correlation would indicate parameter trade-off /
confounding, even if each parameter was recoverable when fitted alone.

The script also retains trial-wise log likelihoods so the same framework
can later be used for ArviZ LOO model comparison.
"""

