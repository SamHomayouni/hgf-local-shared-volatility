def load_model_input(
    environment_dir: Path,
) -> np.ndarray:
    """
    Load the two-stream observations supplied to the HGF.
    """

    input_path = (
        environment_dir
        / "model_runs"
        / "model_input_data.npy"
    )

    if not input_path.exists():
        raise FileNotFoundError(
            f"Could not find model input data: {input_path}"
        )

    input_data = np.load(
        input_path
    )

    if input_data.ndim != 2:
        raise ValueError(
            f"Expected 2D input data, got shape {input_data.shape}."
        )

    if input_data.shape[1] != 2:
        raise ValueError(
            f"Expected two input streams, got shape {input_data.shape}."
        )

    if not np.isfinite(input_data).all():
        raise ValueError(
            "Input data contains non-finite values."
        )

    return input_data.astype(float)


def load_synthetic_responses(
    *,
    environment_dir: Path,
) -> tuple[np.ndarray, dict]:
    """
    Load responses generated by the local-only perceptual model.
    """

    response_dir = (
        environment_dir
        / "synthetic_responses"
        / "local_only"
    )

    response_path = (
        response_dir
        / "synthetic_continuous_predictions.csv"
    )

    metadata_path = (
        response_dir
        / "response_model_metadata.json"
    )

    if not response_path.exists():
        raise FileNotFoundError(
            f"Could not find responses: {response_path}"
        )

    if not metadata_path.exists():
        raise FileNotFoundError(
            f"Could not find metadata: {metadata_path}"
        )

    response_df = pd.read_csv(
        response_path
    )

    with metadata_path.open(
        "r",
        encoding="utf-8",
    ) as file:
        metadata = json.load(file)

    required_columns = {
        "participant_prediction_A",
        "participant_prediction_B",
    }

    missing_columns = (
        required_columns
        - set(response_df.columns)
    )

    if missing_columns:
        raise ValueError(
            "Synthetic response file is missing columns: "
            f"{sorted(missing_columns)}"
        )

    generating_model = metadata.get(
        "generating_perceptual_model"
    )

    if generating_model != "local_only":
        raise ValueError(
            "This test expects behavior generated by local_only, "
            f"but metadata reports {generating_model!r}."
        )

    responses = response_df[
        [
            "participant_prediction_A",
            "participant_prediction_B",
        ]
    ].to_numpy(
        dtype=float
    )

    if not np.isfinite(responses).all():
        raise ValueError(
            "Responses contain non-finite values."
        )

    return (
        responses,
        metadata,
    )


# ---------------------------------------------------------------------
# JAX likelihood functions
# ---------------------------------------------------------------------

def create_likelihood_functions(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
):
    """
    Create total and pointwise log-likelihood functions.

    Free HGF parameters
    -------------------
    value_tonic_volatility
    volatility_tonic_volatility

    Free response parameter
    -----------------------
    log_response_sd
    """

    input_data_jax = jnp.asarray(
        input_data,
        dtype=jnp.float64,
    )

    responses_jax = jnp.asarray(
        responses,
        dtype=jnp.float64,
    )

    n_trials = int(
        len(responses)
    )

    include_mask = jnp.ones(
        n_trials,
        dtype=jnp.float64,
    )

    # Trial zero represents the initial prior state.
    include_mask = (
        include_mask
        .at[0]
        .set(0.0)
    )

    # -------------------------------------------------------------
    # Scalar likelihood for NUTS
    # -------------------------------------------------------------

    @wrap_jax
    def total_logp(
        value,
        log_response_sd,
        value_tonic_volatility,
        volatility_tonic_volatility,
    ):
        """
        Total response log likelihood.
        """

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        value_tonic_volatility = (
            jnp.asarray(
                value_tonic_volatility
            )
            .squeeze()
        )

        volatility_tonic_volatility = (
            jnp.asarray(
                volatility_tonic_volatility
            )
            .squeeze()
        )

        model = build_local_only_model(
            input_precision=(
                input_precision
            ),
            value_tonic_volatility=(
                value_tonic_volatility
            ),
            volatility_tonic_volatility=(
                volatility_tonic_volatility
            ),
            update_type=(
                update_type
            ),
            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        maybe_updated_model = (
            model.input_data(
                input_data=input_data_jax
            )
        )

        if maybe_updated_model is not None:
            model = maybe_updated_model

        response_inputs = (
            jnp.column_stack(
                [
                    value[:, 0],
                    value[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,
                response_function_inputs=(
                    response_inputs
                ),
                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        # Remove trial zero completely.
        return -jnp.sum(
            surprise[1:]
        )

    # -------------------------------------------------------------
    # Pointwise likelihood for future LOO
    # -------------------------------------------------------------

    @wrap_jax
    def pointwise_logp(
        log_response_sd,
        value_tonic_volatility,
        volatility_tonic_volatility,
    ):
        """
        Return one joint A+B log likelihood per included trial.
        """

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        value_tonic_volatility = (
            jnp.asarray(
                value_tonic_volatility
            )
            .squeeze()
        )

        volatility_tonic_volatility = (
            jnp.asarray(
                volatility_tonic_volatility
            )
            .squeeze()
        )

        model = build_local_only_model(
            input_precision=(
                input_precision
            ),
            value_tonic_volatility=(
                value_tonic_volatility
            ),
            volatility_tonic_volatility=(
                volatility_tonic_volatility
            ),
            update_type=(
                update_type
            ),
            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        maybe_updated_model = (
            model.input_data(
                input_data=input_data_jax
            )
        )

        if maybe_updated_model is not None:
            model = maybe_updated_model

        response_inputs = (
            jnp.column_stack(
                [
                    responses_jax[:, 0],
                    responses_jax[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,
                response_function_inputs=(
                    response_inputs
                ),
                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        return -surprise[1:]

    return (
        total_logp,
        pointwise_logp,
    )


# ---------------------------------------------------------------------
# Bayesian fitting
# ---------------------------------------------------------------------

def run_fit(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
    draws: int,
    tune: int,
    chains: int,
    cores: int,
    target_accept: float,
    random_seed: int,
):
    """
    Jointly estimate both tonic volatilities and response noise.
    """

    (
        total_logp,
        pointwise_logp,
    ) = create_likelihood_functions(
        input_data=input_data,
        responses=responses,
        input_precision=input_precision,
        update_type=update_type,
        max_posterior_precision=(
            max_posterior_precision
        ),
    )

    with pm.Model() as model:

        # ---------------------------------------------------------
        # Shared response noise
        # ---------------------------------------------------------

        log_response_sd = pm.Normal(
            "log_response_sd",
            mu=np.log(
                0.20
            ),
            sigma=1.0,
        )

        response_sd = pm.Deterministic(
            "response_sd",
            pm.math.exp(
                log_response_sd
            ),
        )

        # ---------------------------------------------------------
        # Value-state tonic volatility
        # ---------------------------------------------------------

        value_volatility_base = (
            pm.Normal.dist(
                mu=-3.0,
                sigma=5.0,
            )
        )

        value_tonic_volatility = (
            pm.Censored(
                "value_tonic_volatility",
                value_volatility_base,
                lower=-12.0,
                upper=2.0,
                initval=-7.0,
            )
        )

        # ---------------------------------------------------------
        # Volatility-state tonic volatility
        # ---------------------------------------------------------

        volatility_state_base = (
            pm.Normal.dist(
                mu=-3.0,
                sigma=5.0,
            )
        )

        volatility_tonic_volatility = (
            pm.Censored(
                "volatility_tonic_volatility",
                volatility_state_base,
                lower=-12.0,
                upper=2.0,
                initval=-5.0,
            )
        )

        # ---------------------------------------------------------
        # Response likelihood
        # ---------------------------------------------------------

        pm.CustomDist(
            "response_likelihood",
            log_response_sd,
            value_tonic_volatility,
            volatility_tonic_volatility,
            logp=total_logp,
            observed=responses,
        )

        # ---------------------------------------------------------
        # Pointwise likelihood
        # ---------------------------------------------------------

        pm.Deterministic(
            "pointwise_loglikelihood",
            pointwise_logp(
                log_response_sd,
                value_tonic_volatility,
                volatility_tonic_volatility,
            ),
        )

        idata = pm.sample(
            draws=draws,
            tune=tune,
            chains=chains,
            cores=cores,
            backend="jax",
            target_accept=(
                target_accept
            ),
            random_seed=(
                random_seed
            ),
            return_inferencedata=True,
        )

    # Store pointwise likelihood in the standard ArviZ group.
    idata["log_likelihood"] = (
        idata.posterior[
            "pointwise_loglikelihood"
        ]
        .to_dataset(
            name="log_likelihood"
        )
    )

    return (
        model,
        idata,
    )


# ---------------------------------------------------------------------
# Posterior diagnostics
# ---------------------------------------------------------------------

def flatten_posterior(
    idata,
    variable_name: str,
) -> np.ndarray:
    """
    Flatten chain and draw dimensions.
    """

    return (
        idata.posterior[
            variable_name
        ]
        .values
        .reshape(-1)
    )


def calculate_posterior_correlations(
    idata,
) -> dict:
    """
    Calculate pairwise posterior correlations.

    These correlations are especially important for identifying
    possible parameter trade-offs.
    """

    value_samples = flatten_posterior(
        idata,
        "value_tonic_volatility",
    )

    volatility_samples = flatten_posterior(
        idata,
        "volatility_tonic_volatility",
    )

    response_sd_samples = flatten_posterior(
        idata,
        "response_sd",
    )

    value_vs_volatility = float(
        np.corrcoef(
            value_samples,
            volatility_samples,
        )[0, 1]
    )

    value_vs_response_sd = float(
        np.corrcoef(
            value_samples,
            response_sd_samples,
        )[0, 1]
    )

    volatility_vs_response_sd = float(
        np.corrcoef(
            volatility_samples,
            response_sd_samples,
        )[0, 1]
    )

    return {
        "value_tonic_vs_volatility_tonic": (
            value_vs_volatility
        ),
        "value_tonic_vs_response_sd": (
            value_vs_response_sd
        ),
        "volatility_tonic_vs_response_sd": (
            volatility_vs_response_sd
        ),
    }


def summarize_recovery(
    *,
    idata,
    true_response_sd: float,
) -> tuple[
    pd.DataFrame,
    dict,
]:
    """
    Summarize parameter recovery, convergence, and posterior correlations.
    """

    posterior_summary = az.summary(
        idata,
        var_names=[
            "value_tonic_volatility",
            "volatility_tonic_volatility",
            "log_response_sd",
            "response_sd",
        ],
        round_to=4,
    )

    n_divergences = int(
        idata.sample_stats[
            "diverging"
        ]
        .sum()
        .values
    )

    # -------------------------------------------------------------
    # Extract posterior samples
    # -------------------------------------------------------------

    value_samples = flatten_posterior(
        idata,
        "value_tonic_volatility",
    )

    volatility_samples = flatten_posterior(
        idata,
        "volatility_tonic_volatility",
    )

    response_sd_samples = flatten_posterior(
        idata,
        "response_sd",
    )

    # -------------------------------------------------------------
    # HDIs
    # -------------------------------------------------------------

    value_hdi = az.hdi(
        value_samples,
        hdi_prob=0.94,
    )

    volatility_hdi = az.hdi(
        volatility_samples,
        hdi_prob=0.94,
    )

    response_sd_hdi = az.hdi(
        response_sd_samples,
        hdi_prob=0.94,
    )

    # -------------------------------------------------------------
    # Correlations
    # -------------------------------------------------------------

    correlations = (
        calculate_posterior_correlations(
            idata
        )
    )

    # -------------------------------------------------------------
    # Diagnostic dictionary
    # -------------------------------------------------------------

    diagnostics = {

        # ---------------------------------------------------------
        # Value tonic volatility
        # ---------------------------------------------------------

        "true_value_tonic_volatility": float(
            TRUE_VALUE_TONIC_VOLATILITY
        ),

        "posterior_mean_value_tonic_volatility": float(
            np.mean(
                value_samples
            )
        ),

        "value_tonic_volatility_hdi_94_lower": float(
            value_hdi[0]
        ),

        "value_tonic_volatility_hdi_94_upper": float(
            value_hdi[1]
        ),

        "true_value_tonic_volatility_inside_94_hdi": bool(
            value_hdi[0]
            <= TRUE_VALUE_TONIC_VOLATILITY
            <= value_hdi[1]
        ),

        # ---------------------------------------------------------
        # Volatility-state tonic volatility
        # ---------------------------------------------------------

        "true_volatility_tonic_volatility": float(
            TRUE_VOLATILITY_TONIC_VOLATILITY
        ),

        "posterior_mean_volatility_tonic_volatility": float(
            np.mean(
                volatility_samples
            )
        ),

        "volatility_tonic_volatility_hdi_94_lower": float(
            volatility_hdi[0]
        ),

        "volatility_tonic_volatility_hdi_94_upper": float(
            volatility_hdi[1]
        ),

        "true_volatility_tonic_volatility_inside_94_hdi": bool(
            volatility_hdi[0]
            <= TRUE_VOLATILITY_TONIC_VOLATILITY
            <= volatility_hdi[1]
        ),

        # ---------------------------------------------------------
        # Response SD
        # ---------------------------------------------------------

        "true_response_sd": float(
            true_response_sd
        ),

        "posterior_mean_response_sd": float(
            np.mean(
                response_sd_samples
            )
        ),

        "response_sd_hdi_94_lower": float(
            response_sd_hdi[0]
        ),

        "response_sd_hdi_94_upper": float(
            response_sd_hdi[1]
        ),

        "true_response_sd_inside_94_hdi": bool(
            response_sd_hdi[0]
            <= true_response_sd
            <= response_sd_hdi[1]
        ),

        # ---------------------------------------------------------
        # Posterior dependence
        # ---------------------------------------------------------

        "posterior_correlations": (
            correlations
        ),

        "absolute_value_tonic_vs_volatility_tonic_correlation": float(
            abs(
                correlations[
                    "value_tonic_vs_volatility_tonic"
                ]
            )
        ),

        # ---------------------------------------------------------
        # Sampling diagnostics
        # ---------------------------------------------------------

        "n_divergences": (
            n_divergences
        ),
    }

    return (
        posterior_summary,
        diagnostics,
    )


