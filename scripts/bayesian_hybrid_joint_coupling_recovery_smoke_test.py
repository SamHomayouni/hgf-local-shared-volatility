"""
Joint Bayesian coupling-recovery test for the Hybrid HGF.

Free parameters
---------------
1. shared_value_coupling
2. local_volatility_coupling
3. shared response noise SD

Fixed perceptual parameters
---------------------------
value_tonic_volatility        = -7.824
local_vol_tonic_volatility    = -6.0
shared_value_tonic_volatility = -4.0
local_vol_autoconnection      = 0.7
value_autoconnection          = 0.95

Known generating values
-----------------------
shared_value_coupling       = 0.75
local_volatility_coupling   = 0.70
response_sd                 = 0.10

Purpose
-------
Both Hybrid coupling parameters have already recovered well
individually.

This script asks whether they can still be identified when estimated
simultaneously.

Hybrid architecture
-------------------
input A <- value A <- local volatility A <- shared value
input B <- value B <- local volatility B <- shared value

Couplings
---------
shared value -> local volatility:
    shared_value_coupling

local volatility -> value:
    local_volatility_coupling

The main identifiability diagnostic is the posterior correlation
between these two coupling strengths.

Implementation
--------------
The topology is constructed using static Python coupling values:

    shared_value_coupling     = 0.75
    local_volatility_coupling = 0.70

The sampled JAX coupling values are inserted into the already-created
edge attributes before filtering.
"""

