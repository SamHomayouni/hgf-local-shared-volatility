def flatten_samples(
    idata,
    variable_name: str,
) -> np.ndarray:

    return (
        idata.posterior[
            variable_name
        ]
        .values
        .reshape(-1)
    )


def make_correlation_matrix(
    idata,
) -> pd.DataFrame:
    """
    Posterior correlation matrix on natural parameter scales.
    """

    samples = pd.DataFrame(
        {
            "local_volatility_coupling": (
                flatten_samples(
                    idata,
                    "local_volatility_coupling",
                )
            ),

            "shared_value_coupling": (
                flatten_samples(
                    idata,
                    "shared_value_coupling",
                )
            ),

            "response_sd": (
                flatten_samples(
                    idata,
                    "response_sd",
                )
            ),
        }
    )

    return samples.corr()


