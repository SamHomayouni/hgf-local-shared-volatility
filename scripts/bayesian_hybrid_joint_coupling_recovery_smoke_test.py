# Dynamic Hybrid model
# =====================================================================

def build_dynamic_hybrid_model(
    *,
    local_volatility_coupling,
    shared_value_coupling,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
):
    """
    Build Hybrid model with both coupling strengths sampled.
    """

    local_volatility_coupling = (
        jnp.asarray(
            local_volatility_coupling
        )
        .squeeze()
    )

    shared_value_coupling = (
        jnp.asarray(
            shared_value_coupling
        )
        .squeeze()
    )

    # -----------------------------------------------------------------
    # Static graph construction
    # -----------------------------------------------------------------

    model = build_shared_volatility_model(
        input_precision=(
            input_precision
        ),

        value_tonic_volatility=(
            FIXED_VALUE_TONIC_VOLATILITY
        ),

        value_autoconnection_strength=(
            FIXED_VALUE_AUTOCONNECTION
        ),

        local_vol_tonic_volatility=(
            FIXED_LOCAL_VOL_TONIC_VOLATILITY
        ),

        local_volatility_coupling=(
            TRUE_LOCAL_VOLATILITY_COUPLING
        ),

        local_vol_autoconnection_strength=(
            FIXED_LOCAL_VOL_AUTOCONNECTION
        ),

        shared_value_tonic_volatility=(
            FIXED_SHARED_VALUE_TONIC_VOLATILITY
        ),

        shared_value_coupling=(
            TRUE_SHARED_VALUE_COUPLING
        ),

        update_type=(
            update_type
        ),

        max_posterior_precision=(
            max_posterior_precision
        ),
    )

    # -----------------------------------------------------------------
    # Replace both static coupling strengths with sampled JAX values.
    # -----------------------------------------------------------------

    model = set_hybrid_local_volatility_coupling(
        model,
        local_volatility_coupling,
    )

    model = set_hybrid_shared_value_coupling(
        model,
        shared_value_coupling,
    )

    return model


# =====================================================================
# Likelihoods
# =====================================================================

def create_likelihood_functions(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
):

    input_data_jax = jnp.asarray(
        input_data,
        dtype=jnp.float64,
    )

    responses_jax = jnp.asarray(
        responses,
        dtype=jnp.float64,
    )

    n_trials = int(
        len(responses)
    )

    include_mask = jnp.ones(
        n_trials,
        dtype=jnp.float64,
    )

    include_mask = (
        include_mask
        .at[0]
        .set(0.0)
    )

    # =================================================================
    # Total likelihood
    # =================================================================

    @wrap_jax
    def total_logp(
        value,
        log_local_volatility_coupling,
        log_shared_value_coupling,
        log_response_sd,
    ):

        log_local_volatility_coupling = (
            jnp.asarray(
                log_local_volatility_coupling
            )
            .squeeze()
        )

        log_shared_value_coupling = (
            jnp.asarray(
                log_shared_value_coupling
            )
            .squeeze()
        )

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        local_volatility_coupling = jnp.exp(
            log_local_volatility_coupling
        )

        shared_value_coupling = jnp.exp(
            log_shared_value_coupling
        )

        model = build_dynamic_hybrid_model(
            local_volatility_coupling=(
                local_volatility_coupling
            ),

            shared_value_coupling=(
                shared_value_coupling
            ),

            input_precision=(
                input_precision
            ),

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = maybe_updated_model

        response_inputs = (
            jnp.column_stack(
                [
                    value[:, 0],
                    value[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,

                response_function_inputs=(
                    response_inputs
                ),

                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        return -jnp.sum(
            surprise[1:]
        )

    # =================================================================
    # Pointwise likelihood
    # =================================================================

    @wrap_jax
    def pointwise_logp(
        log_local_volatility_coupling,
        log_shared_value_coupling,
        log_response_sd,
    ):

        log_local_volatility_coupling = (
            jnp.asarray(
                log_local_volatility_coupling
            )
            .squeeze()
        )

        log_shared_value_coupling = (
            jnp.asarray(
                log_shared_value_coupling
            )
            .squeeze()
        )

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        local_volatility_coupling = jnp.exp(
            log_local_volatility_coupling
        )

        shared_value_coupling = jnp.exp(
            log_shared_value_coupling
        )

        model = build_dynamic_hybrid_model(
            local_volatility_coupling=(
                local_volatility_coupling
            ),

            shared_value_coupling=(
                shared_value_coupling
            ),

            input_precision=(
                input_precision
            ),

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = maybe_updated_model

        response_inputs = (
            jnp.column_stack(
                [
                    responses_jax[:, 0],
                    responses_jax[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,

                response_function_inputs=(
                    response_inputs
                ),

                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        return -surprise[1:]

    return (
        total_logp,
        pointwise_logp,
    )


# =====================================================================
# Bayesian fit
# =====================================================================

def run_fit(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
    draws: int,
    tune: int,
    chains: int,
    cores: int,
    target_accept: float,
    random_seed: int,
):

    (
        total_logp,
        pointwise_logp,
    ) = create_likelihood_functions(
        input_data=input_data,
        responses=responses,

        input_precision=(
            input_precision
        ),

        update_type=(
            update_type
        ),

        max_posterior_precision=(
            max_posterior_precision
        ),
    )

    with pm.Model() as model:

        # =============================================================
        # Local volatility coupling
        # =============================================================

        log_local_volatility_coupling = pm.Normal(
            "log_local_volatility_coupling",
            mu=0.0,
            sigma=1.0,
        )

        local_volatility_coupling = pm.Deterministic(
            "local_volatility_coupling",

            pm.math.exp(
                log_local_volatility_coupling
            ),
        )

        # =============================================================
        # Shared value coupling
        # =============================================================

        log_shared_value_coupling = pm.Normal(
            "log_shared_value_coupling",
            mu=0.0,
            sigma=1.0,
        )

        shared_value_coupling = pm.Deterministic(
            "shared_value_coupling",

            pm.math.exp(
                log_shared_value_coupling
            ),
        )

        # =============================================================
        # Response noise
        # =============================================================

        log_response_sd = pm.Normal(
            "log_response_sd",

            mu=np.log(
                0.20
            ),

            sigma=1.0,
        )

        response_sd = pm.Deterministic(
            "response_sd",

            pm.math.exp(
                log_response_sd
            ),
        )

        # =============================================================
        # Response likelihood
        # =============================================================

        pm.CustomDist(
            "response_likelihood",

            log_local_volatility_coupling,
            log_shared_value_coupling,
            log_response_sd,

            logp=total_logp,

            observed=responses,
        )

        # =============================================================
        # Pointwise likelihood
        # =============================================================

        pm.Deterministic(
            "pointwise_loglikelihood",

            pointwise_logp(
                log_local_volatility_coupling,
                log_shared_value_coupling,
                log_response_sd,
            ),
        )

        # =============================================================
        # NUTS
        # =============================================================

        idata = pm.sample(
            draws=draws,
            tune=tune,

            chains=chains,
            cores=cores,

            backend="jax",

            target_accept=(
                target_accept
            ),

            random_seed=(
                random_seed
            ),

            return_inferencedata=True,
        )

    idata[
        "log_likelihood"
    ] = (
        idata.posterior[
            "pointwise_loglikelihood"
        ]
        .to_dataset(
            name="log_likelihood"
        )
    )

    return (
        model,
        idata,
    )


# =====================================================================
# Posterior helpers
