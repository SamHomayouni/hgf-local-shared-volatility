def summarize_recovery(
    *,
    idata,
    true_response_sd: float,
) -> tuple[
    pd.DataFrame,
    pd.DataFrame,
    dict,
]:

    posterior_summary = az.summary(
        idata,

        var_names=[
            "log_local_volatility_coupling",
            "local_volatility_coupling",
            "log_shared_value_coupling",
            "shared_value_coupling",
            "log_response_sd",
            "response_sd",
        ],

        round_to=4,
    )

    # -----------------------------------------------------------------
    # Samples
    # -----------------------------------------------------------------

    local_samples = flatten_samples(
        idata,
        "local_volatility_coupling",
    )

    shared_samples = flatten_samples(
        idata,
        "shared_value_coupling",
    )

    response_samples = flatten_samples(
        idata,
        "response_sd",
    )

    # -----------------------------------------------------------------
    # HDIs
    # -----------------------------------------------------------------

    local_hdi = az.hdi(
        local_samples,
        hdi_prob=0.94,
    )

    shared_hdi = az.hdi(
        shared_samples,
        hdi_prob=0.94,
    )

    response_hdi = az.hdi(
        response_samples,
        hdi_prob=0.94,
    )

    # -----------------------------------------------------------------
    # Correlation matrix
    # -----------------------------------------------------------------

    correlation_matrix = (
        make_correlation_matrix(
            idata
        )
    )

    local_vs_shared = float(
        correlation_matrix.loc[
            "local_volatility_coupling",
            "shared_value_coupling",
        ]
    )

    local_vs_response = float(
        correlation_matrix.loc[
            "local_volatility_coupling",
            "response_sd",
        ]
    )

    shared_vs_response = float(
        correlation_matrix.loc[
            "shared_value_coupling",
            "response_sd",
        ]
    )

    # -----------------------------------------------------------------
    # Sampler diagnostics
    # -----------------------------------------------------------------

    n_divergences = int(
        idata.sample_stats[
            "diverging"
        ]
        .sum()
        .values
    )

    maximum_r_hat = float(
        posterior_summary[
            "r_hat"
        ].max()
    )

    minimum_ess_bulk = float(
        posterior_summary[
            "ess_bulk"
        ].min()
    )

    minimum_ess_tail = float(
        posterior_summary[
            "ess_tail"
        ].min()
    )

    diagnostics = {

        # =============================================================
        # Fixed parameters
        # =============================================================

        "fixed_value_tonic_volatility": float(
            FIXED_VALUE_TONIC_VOLATILITY
        ),

        "fixed_local_vol_tonic_volatility": float(
            FIXED_LOCAL_VOL_TONIC_VOLATILITY
        ),

        "fixed_shared_value_tonic_volatility": float(
            FIXED_SHARED_VALUE_TONIC_VOLATILITY
        ),

        "fixed_local_vol_autoconnection": float(
            FIXED_LOCAL_VOL_AUTOCONNECTION
        ),

        # =============================================================
        # Local volatility coupling
        # =============================================================

        "true_local_volatility_coupling": float(
            TRUE_LOCAL_VOLATILITY_COUPLING
        ),

        "posterior_mean_local_volatility_coupling": float(
            np.mean(
                local_samples
            )
        ),

        "posterior_median_local_volatility_coupling": float(
            np.median(
                local_samples
            )
        ),

        "local_volatility_coupling_hdi_94_lower": float(
            local_hdi[0]
        ),

        "local_volatility_coupling_hdi_94_upper": float(
            local_hdi[1]
        ),

        "true_local_volatility_coupling_inside_94_hdi": bool(
            local_hdi[0]
            <= TRUE_LOCAL_VOLATILITY_COUPLING
            <= local_hdi[1]
        ),

        # =============================================================
        # Shared value coupling
        # =============================================================

        "true_shared_value_coupling": float(
            TRUE_SHARED_VALUE_COUPLING
        ),

        "posterior_mean_shared_value_coupling": float(
            np.mean(
                shared_samples
            )
        ),

        "posterior_median_shared_value_coupling": float(
            np.median(
                shared_samples
            )
        ),

        "shared_value_coupling_hdi_94_lower": float(
            shared_hdi[0]
        ),

        "shared_value_coupling_hdi_94_upper": float(
            shared_hdi[1]
        ),

        "true_shared_value_coupling_inside_94_hdi": bool(
            shared_hdi[0]
            <= TRUE_SHARED_VALUE_COUPLING
            <= shared_hdi[1]
        ),

        # =============================================================
        # Response noise
        # =============================================================

        "true_response_sd": float(
            true_response_sd
        ),

        "posterior_mean_response_sd": float(
            np.mean(
                response_samples
            )
        ),

        "posterior_median_response_sd": float(
            np.median(
                response_samples
            )
        ),

        "response_sd_hdi_94_lower": float(
            response_hdi[0]
        ),

        "response_sd_hdi_94_upper": float(
            response_hdi[1]
        ),

        "true_response_sd_inside_94_hdi": bool(
            response_hdi[0]
            <= true_response_sd
            <= response_hdi[1]
        ),

        # =============================================================
        # Posterior dependence
        # =============================================================

        "posterior_correlations": {

            "local_volatility_coupling_vs_shared_value_coupling": (
                local_vs_shared
            ),

            "local_volatility_coupling_vs_response_sd": (
                local_vs_response
            ),

            "shared_value_coupling_vs_response_sd": (
                shared_vs_response
            ),
        },

        "absolute_local_vs_shared_coupling_correlation": float(
            abs(
                local_vs_shared
            )
        ),

        # =============================================================
        # Sampling
        # =============================================================

        "n_divergences": (
            n_divergences
        ),

        "maximum_r_hat": (
            maximum_r_hat
        ),

        "minimum_ess_bulk": (
            minimum_ess_bulk
        ),

        "minimum_ess_tail": (
            minimum_ess_tail
        ),
    }

    return (
        posterior_summary,
        correlation_matrix,
        diagnostics,
    )


