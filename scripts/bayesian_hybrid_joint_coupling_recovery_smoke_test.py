# Local volatility coupling manipulation
# =====================================================================

def set_volatility_edge_coupling(
    model,
    *,
    parent_idx: int,
    child_idx: int,
    coupling,
):
    """
    Replace one existing volatility-coupling strength.

    pyHGF stores volatility coupling on both sides:

        child:
            volatility_coupling_parents

        parent:
            volatility_coupling_children

    Both are updated while keeping graph topology fixed.
    """

    coupling = (
        jnp.asarray(
            coupling
        )
        .squeeze()
    )

    # -----------------------------------------------------------------
    # Child side
    # -----------------------------------------------------------------

    volatility_parents = (
        model.edges[
            child_idx
        ].volatility_parents
    )

    if volatility_parents is None:
        raise ValueError(
            f"Node {child_idx} has no volatility parents."
        )

    try:
        parent_position = (
            volatility_parents.index(
                parent_idx
            )
        )

    except ValueError as error:
        raise ValueError(
            f"Node {parent_idx} is not a volatility parent "
            f"of node {child_idx}."
        ) from error

    # -----------------------------------------------------------------
    # Parent side
    # -----------------------------------------------------------------

    volatility_children = (
        model.edges[
            parent_idx
        ].volatility_children
    )

    if volatility_children is None:
        raise ValueError(
            f"Node {parent_idx} has no volatility children."
        )

    try:
        child_position = (
            volatility_children.index(
                child_idx
            )
        )

    except ValueError as error:
        raise ValueError(
            f"Node {child_idx} is not a volatility child "
            f"of node {parent_idx}."
        ) from error

    # -----------------------------------------------------------------
    # Child-side value
    # -----------------------------------------------------------------

    child_couplings = (
        model.attributes[
            child_idx
        ][
            "volatility_coupling_parents"
        ]
    )

    model.attributes[
        child_idx
    ][
        "volatility_coupling_parents"
    ] = (
        child_couplings
        .at[
            parent_position
        ]
        .set(
            coupling
        )
    )

    # -----------------------------------------------------------------
    # Parent-side value
    # -----------------------------------------------------------------

    parent_couplings = (
        model.attributes[
            parent_idx
        ][
            "volatility_coupling_children"
        ]
    )

    model.attributes[
        parent_idx
    ][
        "volatility_coupling_children"
    ] = (
        parent_couplings
        .at[
            child_position
        ]
        .set(
            coupling
        )
    )

    return model


def set_hybrid_local_volatility_coupling(
    model,
    local_volatility_coupling,
):
    """
    Apply one common local volatility coupling to both streams.
    """

    model = set_volatility_edge_coupling(
        model,
        parent_idx=LOCAL_VOL_A_NODE,
        child_idx=VALUE_A_NODE,
        coupling=local_volatility_coupling,
    )

    model = set_volatility_edge_coupling(
        model,
        parent_idx=LOCAL_VOL_B_NODE,
        child_idx=VALUE_B_NODE,
        coupling=local_volatility_coupling,
    )

    return model


# =====================================================================
# Shared value coupling manipulation
# =====================================================================

def set_hybrid_shared_value_coupling(
    model,
    shared_value_coupling,
):
    """
    Apply one common shared-value coupling to:

        shared value -> local volatility A
        shared value -> local volatility B
    """

    shared_value_coupling = (
        jnp.asarray(
            shared_value_coupling
        )
        .squeeze()
    )

    set_coupling(
        attributes=model.attributes,
        edges=model.edges,
        parent_idx=SHARED_VALUE_NODE,
        child_idx=LOCAL_VOL_A_NODE,
        coupling=shared_value_coupling,
    )

    set_coupling(
        attributes=model.attributes,
        edges=model.edges,
        parent_idx=SHARED_VALUE_NODE,
        child_idx=LOCAL_VOL_B_NODE,
        coupling=shared_value_coupling,
    )

    return model


