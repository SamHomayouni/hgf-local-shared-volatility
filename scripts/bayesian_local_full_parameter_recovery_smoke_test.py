"""
Joint Bayesian parameter-recovery test for the Local-only HGF.

Free parameters
---------------
1. value_tonic_volatility
2. volatility_tonic_volatility
3. volatility_coupling
4. shared response noise SD

Known generating values
-----------------------
value_tonic_volatility      = -7.824
volatility_tonic_volatility = -6.0
volatility_coupling         = 1.0
response_sd                 = 0.10

Purpose
-------
All three perceptual parameters have already been tested separately.

This script asks whether they remain identifiable when estimated
simultaneously.

The most important issue is parameter trade-off, particularly between:

    value_tonic_volatility
    volatility_tonic_volatility
    volatility_coupling

because different combinations of these parameters can potentially
produce similar effective learning dynamics.

Implementation detail
---------------------
The volatility-coupling edge topology is constructed using the static
Python value:

    volatility_coupling = 1.0

The sampled JAX coupling is inserted into the existing pyHGF coupling
attributes AFTER network construction.

This avoids passing a JAX tracer into pyHGF's add_edges() machinery.

Pointwise log likelihoods are also retained for the later PSIS-LOO
model-recovery stage.
"""

