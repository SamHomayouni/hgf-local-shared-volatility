    (
        responses,
        response_metadata,
    ) = load_synthetic_responses(
        environment_dir=environment_dir,
    )

    if len(input_data) != len(responses):
        raise ValueError(
            "Number of input trials and response trials "
            "does not match."
        )

    # -------------------------------------------------------------
    # True response SD
    # -------------------------------------------------------------

    true_response_sd_A = float(
        response_metadata[
            "response_sd_A"
        ]
    )

    true_response_sd_B = float(
        response_metadata[
            "response_sd_B"
        ]
    )

    if not np.isclose(
        true_response_sd_A,
        true_response_sd_B,
    ):
        raise ValueError(
            "This test assumes one shared response SD."
        )

    true_response_sd = (
        true_response_sd_A
    )

    print(
        f"    response SD:                 "
        f"{true_response_sd}"
    )

    print(
        f"\nTrials total: "
        f"{len(responses)}"
    )

    print(
        f"Trials in likelihood: "
        f"{len(responses) - 1}"
    )

