def build_dynamic_global_model(
    *,
    value_tonic_volatility,
    shared_volatility_coupling,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
):
    """
    Construct the Global model with:

        free value tonic volatility
        free shared volatility coupling
        fixed shared volatility tonic volatility
    """

    value_tonic_volatility = (
        jnp.asarray(
            value_tonic_volatility
        )
        .squeeze()
    )

    shared_volatility_coupling = (
        jnp.asarray(
            shared_volatility_coupling
        )
        .squeeze()
    )

    # -----------------------------------------------------------------
    # Build static graph.
    # -----------------------------------------------------------------

    model = build_global_only_model(
        input_precision=(
            input_precision
        ),

        value_tonic_volatility=(
            value_tonic_volatility
        ),

        shared_volatility_tonic_volatility=(
            FIXED_SHARED_VOLATILITY_TONIC_VOLATILITY
        ),

        # Static topology-construction value.
        shared_volatility_coupling=1.0,

        update_type=(
            update_type
        ),

        max_posterior_precision=(
            max_posterior_precision
        ),
    )

    # -----------------------------------------------------------------
    # Insert sampled coupling.
    # -----------------------------------------------------------------

    model = set_global_shared_volatility_coupling(
        model,
        shared_volatility_coupling,
    )

    return model


