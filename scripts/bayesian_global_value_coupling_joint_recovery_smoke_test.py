def set_volatility_edge_coupling(
    model,
    *,
    parent_idx: int,
    child_idx: int,
    coupling,
):
    """
    Replace the numerical coupling strength on one existing
    volatility edge without altering network topology.
    """

    coupling = (
        jnp.asarray(coupling)
        .squeeze()
    )

    # -----------------------------------------------------------------
    # Locate parent from child side.
    # -----------------------------------------------------------------

    volatility_parents = (
        model.edges[
            child_idx
        ].volatility_parents
    )

    if volatility_parents is None:
        raise ValueError(
            f"Node {child_idx} has no volatility parents."
        )

    try:
        parent_position = (
            volatility_parents.index(
                parent_idx
            )
        )

    except ValueError as error:
        raise ValueError(
            f"Node {parent_idx} is not a volatility parent "
            f"of node {child_idx}."
        ) from error

    # -----------------------------------------------------------------
    # Locate child from parent side.
    # -----------------------------------------------------------------

    volatility_children = (
        model.edges[
            parent_idx
        ].volatility_children
    )

    if volatility_children is None:
        raise ValueError(
            f"Node {parent_idx} has no volatility children."
        )

    try:
        child_position = (
            volatility_children.index(
                child_idx
            )
        )

    except ValueError as error:
        raise ValueError(
            f"Node {child_idx} is not a volatility child "
            f"of node {parent_idx}."
        ) from error

    # -----------------------------------------------------------------
    # Child-side representation.
    # -----------------------------------------------------------------

    child_couplings = (
        model.attributes[
            child_idx
        ][
            "volatility_coupling_parents"
        ]
    )

    model.attributes[
        child_idx
    ][
        "volatility_coupling_parents"
    ] = (
        child_couplings
        .at[parent_position]
        .set(coupling)
    )

    # -----------------------------------------------------------------
    # Parent-side representation.
    # -----------------------------------------------------------------

    parent_couplings = (
        model.attributes[
            parent_idx
        ][
            "volatility_coupling_children"
        ]
    )

    model.attributes[
        parent_idx
    ][
        "volatility_coupling_children"
    ] = (
        parent_couplings
        .at[child_position]
        .set(coupling)
    )

    return model


def set_global_shared_volatility_coupling(
    model,
    shared_volatility_coupling,
):
    """
    Apply the same sampled coupling to both Global edges:

        shared volatility -> value A
        shared volatility -> value B
    """

    model = set_volatility_edge_coupling(
        model,
        parent_idx=SHARED_VOLATILITY_NODE,
        child_idx=VALUE_A_NODE,
        coupling=shared_volatility_coupling,
    )

    model = set_volatility_edge_coupling(
        model,
        parent_idx=SHARED_VOLATILITY_NODE,
        child_idx=VALUE_B_NODE,
        coupling=shared_volatility_coupling,
    )

    return model


