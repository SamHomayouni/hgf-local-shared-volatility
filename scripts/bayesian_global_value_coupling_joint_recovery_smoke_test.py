"""
Reduced joint Bayesian recovery test for the Global-only HGF.

Free parameters
---------------
1. value_tonic_volatility
2. shared_volatility_coupling
3. shared response noise SD

Fixed perceptual parameter
--------------------------
shared_volatility_tonic_volatility = -6.0

Known generating values
-----------------------
value_tonic_volatility      = -7.824
shared_volatility_coupling  = 1.0
response_sd                 = 0.10

Purpose
-------
The Global model showed severe confounding between:

    shared_volatility_tonic_volatility
    shared_volatility_coupling

Therefore this test fixes the shared-volatility tonic parameter and
tests whether value tonic volatility and shared volatility coupling
can be jointly recovered.

If successful, this becomes the candidate parameterization for the
Global model in formal model recovery.

Implementation detail
---------------------
The pyHGF network topology is constructed with static:

    shared_volatility_coupling = 1.0

The sampled JAX coupling is inserted into the existing coupling arrays
after graph construction and before filtering.
"""

