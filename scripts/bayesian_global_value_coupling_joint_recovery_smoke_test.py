def load_model_input(
    environment_dir: Path,
) -> np.ndarray:
    """
    Load the two-stream observations supplied to the HGF.
    """

    input_path = (
        environment_dir
        / "model_runs"
        / "model_input_data.npy"
    )

    if not input_path.exists():
        raise FileNotFoundError(
            f"Could not find model input: {input_path}"
        )

    input_data = np.load(
        input_path
    )

    if input_data.ndim != 2:
        raise ValueError(
            f"Expected 2D input, got {input_data.shape}."
        )

    if input_data.shape[1] != 2:
        raise ValueError(
            f"Expected two streams, got {input_data.shape}."
        )

    if not np.isfinite(input_data).all():
        raise ValueError(
            "Input contains non-finite values."
        )

    return input_data.astype(float)


def load_synthetic_responses(
    *,
    environment_dir: Path,
) -> tuple[np.ndarray, dict]:
    """
    Load behavior generated by the Global-only model.
    """

    response_dir = (
        environment_dir
        / "synthetic_responses"
        / "global_only"
    )

    response_path = (
        response_dir
        / "synthetic_continuous_predictions.csv"
    )

    metadata_path = (
        response_dir
        / "response_model_metadata.json"
    )

    if not response_path.exists():
        raise FileNotFoundError(
            f"Could not find responses: {response_path}"
        )

    if not metadata_path.exists():
        raise FileNotFoundError(
            f"Could not find metadata: {metadata_path}"
        )

    response_df = pd.read_csv(
        response_path
    )

    with metadata_path.open(
        "r",
        encoding="utf-8",
    ) as file:
        metadata = json.load(file)

    required_columns = {
        "participant_prediction_A",
        "participant_prediction_B",
    }

    missing = (
        required_columns
        - set(response_df.columns)
    )

    if missing:
        raise ValueError(
            "Response file is missing columns: "
            f"{sorted(missing)}"
        )

    generating_model = metadata.get(
        "generating_perceptual_model"
    )

    if generating_model != "global_only":
        raise ValueError(
            "This test expects Global-generated behavior, "
            f"but metadata reports {generating_model!r}."
        )

    responses = response_df[
        [
            "participant_prediction_A",
            "participant_prediction_B",
        ]
    ].to_numpy(
        dtype=float
    )

    if not np.isfinite(responses).all():
        raise ValueError(
            "Responses contain non-finite values."
        )

    return (
        responses,
        metadata,
    )


