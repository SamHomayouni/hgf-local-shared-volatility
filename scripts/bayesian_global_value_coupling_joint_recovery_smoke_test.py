def flatten_samples(
    idata,
    variable_name: str,
) -> np.ndarray:
    """
    Flatten chains and draws.
    """

    return (
        idata.posterior[
            variable_name
        ]
        .values
        .reshape(-1)
    )


def make_correlation_matrix(
    idata,
) -> pd.DataFrame:
    """
    Posterior correlation matrix on interpretable parameter scales.
    """

    samples = pd.DataFrame(
        {
            "value_tonic_volatility": (
                flatten_samples(
                    idata,
                    "value_tonic_volatility",
                )
            ),

            "shared_volatility_coupling": (
                flatten_samples(
                    idata,
                    "shared_volatility_coupling",
                )
            ),

            "response_sd": (
                flatten_samples(
                    idata,
                    "response_sd",
                )
            ),
        }
    )

    return samples.corr()


