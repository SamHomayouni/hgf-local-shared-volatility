def summarize_recovery(
    *,
    idata,
    true_response_sd: float,
) -> tuple[
    pd.DataFrame,
    pd.DataFrame,
    dict,
]:
    """
    Summarize recovery and posterior dependence.
    """

    posterior_summary = az.summary(
        idata,

        var_names=[
            "value_tonic_volatility",
            "log_shared_volatility_coupling",
            "shared_volatility_coupling",
            "log_response_sd",
            "response_sd",
        ],

        round_to=4,
    )

    # -----------------------------------------------------------------
    # Samples
    # -----------------------------------------------------------------

    value_samples = flatten_samples(
        idata,
        "value_tonic_volatility",
    )

    coupling_samples = flatten_samples(
        idata,
        "shared_volatility_coupling",
    )

    response_sd_samples = flatten_samples(
        idata,
        "response_sd",
    )

    # -----------------------------------------------------------------
    # HDIs
    # -----------------------------------------------------------------

    value_hdi = az.hdi(
        value_samples,
        hdi_prob=0.94,
    )

    coupling_hdi = az.hdi(
        coupling_samples,
        hdi_prob=0.94,
    )

    response_sd_hdi = az.hdi(
        response_sd_samples,
        hdi_prob=0.94,
    )

    # -----------------------------------------------------------------
    # Correlations
    # -----------------------------------------------------------------

    correlation_matrix = (
        make_correlation_matrix(
            idata
        )
    )

    value_vs_coupling = float(
        correlation_matrix.loc[
            "value_tonic_volatility",
            "shared_volatility_coupling",
        ]
    )

    value_vs_response = float(
        correlation_matrix.loc[
            "value_tonic_volatility",
            "response_sd",
        ]
    )

    coupling_vs_response = float(
        correlation_matrix.loc[
            "shared_volatility_coupling",
            "response_sd",
        ]
    )

    # -----------------------------------------------------------------
    # Sampling diagnostics
    # -----------------------------------------------------------------

    n_divergences = int(
        idata.sample_stats[
            "diverging"
        ]
        .sum()
        .values
    )

    maximum_r_hat = float(
        posterior_summary[
            "r_hat"
        ].max()
    )

    minimum_ess_bulk = float(
        posterior_summary[
            "ess_bulk"
        ].min()
    )

    minimum_ess_tail = float(
        posterior_summary[
            "ess_tail"
        ].min()
    )

    diagnostics = {

        # =============================================================
        # Fixed parameter
        # =============================================================

        "fixed_shared_volatility_tonic_volatility": float(
            FIXED_SHARED_VOLATILITY_TONIC_VOLATILITY
        ),

        # =============================================================
        # Value tonic volatility
        # =============================================================

        "true_value_tonic_volatility": float(
            TRUE_VALUE_TONIC_VOLATILITY
        ),

        "posterior_mean_value_tonic_volatility": float(
            np.mean(
                value_samples
            )
        ),

        "posterior_median_value_tonic_volatility": float(
            np.median(
                value_samples
            )
        ),

        "value_tonic_volatility_hdi_94_lower": float(
            value_hdi[0]
        ),

        "value_tonic_volatility_hdi_94_upper": float(
            value_hdi[1]
        ),

        "true_value_tonic_volatility_inside_94_hdi": bool(
            value_hdi[0]
            <= TRUE_VALUE_TONIC_VOLATILITY
            <= value_hdi[1]
        ),

        # =============================================================
        # Shared coupling
        # =============================================================

        "true_shared_volatility_coupling": float(
            TRUE_SHARED_VOLATILITY_COUPLING
        ),

        "posterior_mean_shared_volatility_coupling": float(
            np.mean(
                coupling_samples
            )
        ),

        "posterior_median_shared_volatility_coupling": float(
            np.median(
                coupling_samples
            )
        ),

        "shared_volatility_coupling_hdi_94_lower": float(
            coupling_hdi[0]
        ),

        "shared_volatility_coupling_hdi_94_upper": float(
            coupling_hdi[1]
        ),

        "true_shared_volatility_coupling_inside_94_hdi": bool(
            coupling_hdi[0]
            <= TRUE_SHARED_VOLATILITY_COUPLING
            <= coupling_hdi[1]
        ),

        # =============================================================
        # Response SD
        # =============================================================

        "true_response_sd": float(
            true_response_sd
        ),

        "posterior_mean_response_sd": float(
            np.mean(
                response_sd_samples
            )
        ),

        "posterior_median_response_sd": float(
            np.median(
                response_sd_samples
            )
        ),

        "response_sd_hdi_94_lower": float(
            response_sd_hdi[0]
        ),

        "response_sd_hdi_94_upper": float(
            response_sd_hdi[1]
        ),

        "true_response_sd_inside_94_hdi": bool(
            response_sd_hdi[0]
            <= true_response_sd
            <= response_sd_hdi[1]
        ),

        # =============================================================
        # Posterior correlations
        # =============================================================

        "posterior_correlations": {

            "value_tonic_vs_shared_coupling": (
                value_vs_coupling
            ),

            "value_tonic_vs_response_sd": (
                value_vs_response
            ),

            "shared_coupling_vs_response_sd": (
                coupling_vs_response
            ),
        },

        "absolute_value_tonic_vs_shared_coupling_correlation": float(
            abs(
                value_vs_coupling
            )
        ),

        # =============================================================
        # Sampling
        # =============================================================

        "n_divergences": (
            n_divergences
        ),

        "maximum_r_hat": (
            maximum_r_hat
        ),

        "minimum_ess_bulk": (
            minimum_ess_bulk
        ),

        "minimum_ess_tail": (
            minimum_ess_tail
        ),
    }

    return (
        posterior_summary,
        correlation_matrix,
        diagnostics,
    )


