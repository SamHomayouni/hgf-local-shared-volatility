# Likelihoods
# =====================================================================

def create_likelihood_functions(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
):
    """
    Create scalar and pointwise JAX likelihood functions.
    """

    input_data_jax = jnp.asarray(
        input_data,
        dtype=jnp.float64,
    )

    responses_jax = jnp.asarray(
        responses,
        dtype=jnp.float64,
    )

    n_trials = int(
        len(responses)
    )

    include_mask = jnp.ones(
        n_trials,
        dtype=jnp.float64,
    )

    # Exclude initial prior trial.
    include_mask = (
        include_mask
        .at[0]
        .set(0.0)
    )

    # =================================================================
    # Total likelihood
    # =================================================================

    @wrap_jax
    def total_logp(
        value,
        value_tonic_volatility,
        log_shared_volatility_coupling,
        log_response_sd,
    ):
        """
        Scalar response log likelihood for NUTS.
        """

        value_tonic_volatility = (
            jnp.asarray(
                value_tonic_volatility
            )
            .squeeze()
        )

        log_shared_volatility_coupling = (
            jnp.asarray(
                log_shared_volatility_coupling
            )
            .squeeze()
        )

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        shared_volatility_coupling = jnp.exp(
            log_shared_volatility_coupling
        )

        model = build_dynamic_global_model(
            value_tonic_volatility=(
                value_tonic_volatility
            ),

            shared_volatility_coupling=(
                shared_volatility_coupling
            ),

            input_precision=(
                input_precision
            ),

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = maybe_updated_model

        response_inputs = (
            jnp.column_stack(
                [
                    value[:, 0],
                    value[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,

                response_function_inputs=(
                    response_inputs
                ),

                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        return -jnp.sum(
            surprise[1:]
        )

    # =================================================================
    # Pointwise likelihood
    # =================================================================

    @wrap_jax
    def pointwise_logp(
        value_tonic_volatility,
        log_shared_volatility_coupling,
        log_response_sd,
    ):
        """
        Return one A+B log likelihood per included trial.
        """

        value_tonic_volatility = (
            jnp.asarray(
                value_tonic_volatility
            )
            .squeeze()
        )

        log_shared_volatility_coupling = (
            jnp.asarray(
                log_shared_volatility_coupling
            )
            .squeeze()
        )

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        shared_volatility_coupling = jnp.exp(
            log_shared_volatility_coupling
        )

        model = build_dynamic_global_model(
            value_tonic_volatility=(
                value_tonic_volatility
            ),

            shared_volatility_coupling=(
                shared_volatility_coupling
            ),

            input_precision=(
                input_precision
            ),

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = maybe_updated_model

        response_inputs = (
            jnp.column_stack(
                [
                    responses_jax[:, 0],
                    responses_jax[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,

                response_function_inputs=(
                    response_inputs
                ),

                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        return -surprise[1:]

    return (
        total_logp,
        pointwise_logp,
    )


# =====================================================================
# Bayesian fit
# =====================================================================

def run_fit(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
    draws: int,
    tune: int,
    chains: int,
    cores: int,
    target_accept: float,
    random_seed: int,
):
    """
    Fit value tonic volatility, shared coupling, and response SD.
    """

    (
        total_logp,
        pointwise_logp,
    ) = create_likelihood_functions(
        input_data=input_data,
        responses=responses,

        input_precision=(
            input_precision
        ),

        update_type=(
            update_type
        ),

        max_posterior_precision=(
            max_posterior_precision
        ),
    )

    with pm.Model() as model:

        # =============================================================
        # Value tonic volatility
        # =============================================================

        value_base = (
            pm.Normal.dist(
                mu=-3.0,
                sigma=5.0,
            )
        )

        value_tonic_volatility = (
            pm.Censored(
                "value_tonic_volatility",

                value_base,

                lower=-12.0,
                upper=2.0,

                initval=-7.0,
            )
        )

        # =============================================================
        # Shared volatility coupling
        # =============================================================

        log_shared_volatility_coupling = (
            pm.Normal(
                "log_shared_volatility_coupling",
                mu=0.0,
                sigma=1.0,
            )
        )

        shared_volatility_coupling = (
            pm.Deterministic(
                "shared_volatility_coupling",

                pm.math.exp(
                    log_shared_volatility_coupling
                ),
            )
        )

        # =============================================================
        # Response noise
        # =============================================================

        log_response_sd = (
            pm.Normal(
                "log_response_sd",

                mu=np.log(
                    0.20
                ),

                sigma=1.0,
            )
        )

        response_sd = (
            pm.Deterministic(
                "response_sd",

                pm.math.exp(
                    log_response_sd
                ),
            )
        )

        # =============================================================
        # Response likelihood
        # =============================================================

        pm.CustomDist(
            "response_likelihood",

            value_tonic_volatility,
            log_shared_volatility_coupling,
            log_response_sd,

            logp=total_logp,

            observed=responses,
        )

        # =============================================================
        # Pointwise log likelihood
        # =============================================================

        pm.Deterministic(
            "pointwise_loglikelihood",

            pointwise_logp(
                value_tonic_volatility,
                log_shared_volatility_coupling,
                log_response_sd,
            ),
        )

        # =============================================================
        # NUTS
        # =============================================================

        idata = pm.sample(
            draws=draws,
            tune=tune,

            chains=chains,
            cores=cores,

            backend="jax",

            target_accept=(
                target_accept
            ),

            random_seed=(
                random_seed
            ),

            return_inferencedata=True,
        )

    # -----------------------------------------------------------------
    # Standard ArviZ log_likelihood group.
    # -----------------------------------------------------------------

    idata[
        "log_likelihood"
    ] = (
        idata.posterior[
            "pointwise_loglikelihood"
        ]
        .to_dataset(
            name="log_likelihood"
        )
    )

    return (
        model,
        idata,
    )


