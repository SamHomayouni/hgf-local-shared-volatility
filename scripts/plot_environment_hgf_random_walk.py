"""
Plot the generated HGF-style two-stream random-walk environment.

This script reads the environment generated by:

    src/environments/two_stream_hgf_random_walk.py

and saves diagnostic plots showing:
    - observations and latent means for each stream
    - latent means of both streams together
    - process variance schedule
    - process standard deviation schedule
    - latent innovations
    - observation noise

Expected input
--------------
By default, this script reads:

    outputs/hgf_walk_outputs/environment_long.csv

Expected output
---------------
By default, this script writes figures to:

    outputs/hgf_walk_outputs/figures/environment/
"""

from __future__ import annotations

from pathlib import Path
import argparse

import matplotlib.pyplot as plt
import pandas as pd


DEFAULT_ENVIRONMENT_PATH = Path("outputs/hgf_walk_outputs/environment_long.csv")
DEFAULT_FIGURE_DIR = Path("outputs/hgf_walk_outputs/figures/environment")


def load_environment(environment_path: str | Path) -> pd.DataFrame:
    """
    Load and validate the long-format environment dataframe.
    """

    environment_path = Path(environment_path)

    if not environment_path.exists():
        raise FileNotFoundError(
            f"Could not find {environment_path}. "
            "Run src/environments/two_stream_hgf_random_walk.py first."
        )

    environment_df = pd.read_csv(environment_path)

    required_columns = {
        "trial_index",
        "trial",
        "stream",
        "block",
        "regime",
        "latent_mean",
        "observation",
        "changepoint",
        "process_variance",
        "process_sd",
        "latent_innovation",
        "observation_noise",
        "is_a_volatile_block",
    }

    missing_columns = required_columns - set(environment_df.columns)

    if missing_columns:
        raise ValueError(
            f"Environment file is missing required columns: "
            f"{sorted(missing_columns)}"
        )

    return environment_df


def get_volatile_blocks(environment_df: pd.DataFrame) -> list[tuple[int, int, str, str]]:
    """
    Return blocks in which either stream is objectively volatile.

    Returns
    -------
    list[tuple[int, int, str, str]]

    Each tuple contains:
        start_index
        stop_index
        block_name
        volatility_label

    volatility_label is one of:
        "A volatile"
        "B volatile"
        "A + B volatile"
    """

    regimes_wide = (
        environment_df.pivot_table(
            index=["trial_index", "block"],
            columns="stream",
            values="regime",
            aggfunc="first",
        )
        .reset_index()
        .sort_values("trial_index")
    )

    volatile_rows = regimes_wide[
        (regimes_wide["A"] == "volatile")
        | (regimes_wide["B"] == "volatile")
    ]

    ranges: list[tuple[int, int, str, str]] = []

    for block_name, block_df in volatile_rows.groupby(
        "block",
        sort=False,
    ):
        start_index = int(block_df["trial_index"].min())
        stop_index = int(block_df["trial_index"].max()) + 1

        a_volatile = bool((block_df["A"] == "volatile").any())
        b_volatile = bool((block_df["B"] == "volatile").any())

        if a_volatile and b_volatile:
            volatility_label = "A + B volatile"
        elif a_volatile:
            volatility_label = "A volatile"
        else:
            volatility_label = "B volatile"

        ranges.append(
            (
                start_index,
                stop_index,
                str(block_name),
                volatility_label,
            )
        )

    return ranges



def add_volatile_block_shading(axis, environment_df: pd.DataFrame) -> None:
    """
    Shade blocks where either A, B, or both streams are volatile.
    """

    volatile_ranges = get_volatile_blocks(environment_df)

    used_labels: set[str] = set()

    for (
        start_index,
        stop_index,
        block_name,
        volatility_label,
    ) in volatile_ranges:

        legend_label = (
            volatility_label
            if volatility_label not in used_labels
            else None
        )

        axis.axvspan(
            start_index,
            stop_index,
            alpha=0.15,
            label=legend_label,
        )

        used_labels.add(volatility_label)

        y_min, y_max = axis.get_ylim()

        axis.text(
            x=(start_index + stop_index) / 2,
            y=y_max,
            s=f"{block_name}\n{volatility_label}",
            ha="center",
            va="top",
            fontsize=9,
        )


def save_figure(fig, output_path: Path) -> None:
    """
    Save and close a matplotlib figure.
    """

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    fig.savefig(output_path, dpi=150)
    plt.close(fig)

    print(f"Saved: {output_path}")


def plot_stream(
    *,
    environment_df: pd.DataFrame,
    stream: str,
    figure_dir: Path,
) -> None:
    """
    Plot one stream's latent mean and observations.
    """

    stream_df = environment_df[environment_df["stream"] == stream].copy()

    fig, axis = plt.subplots(figsize=(12, 4))

    axis.plot(
        stream_df["trial_index"],
        stream_df["observation"],
        linewidth=0.7,
        label=f"observation {stream}",
    )

    axis.plot(
        stream_df["trial_index"],
        stream_df["latent_mean"],
        linewidth=2.0,
        label=f"latent mean {stream}",
    )

    add_volatile_block_shading(axis, environment_df)

    axis.set_title(f"HGF-style random-walk environment — stream {stream}")
    axis.set_xlabel("Trial index")
    axis.set_ylabel("Value")
    axis.legend(loc="best")

    output_path = figure_dir / f"hgf_random_walk_stream_{stream}.png"
    save_figure(fig, output_path)


def plot_both_latent_means(
    *,
    environment_df: pd.DataFrame,
    figure_dir: Path,
) -> None:
    """
    Plot latent means of both streams together.
    """

    fig, axis = plt.subplots(figsize=(12, 4))

    for stream in ["A", "B"]:
        stream_df = environment_df[environment_df["stream"] == stream]

        axis.plot(
            stream_df["trial_index"],
            stream_df["latent_mean"],
            linewidth=2.0,
            label=f"latent mean {stream}",
        )

    add_volatile_block_shading(axis, environment_df)

    axis.set_title("HGF-style random-walk environment — latent means")
    axis.set_xlabel("Trial index")
    axis.set_ylabel("Latent mean")
    axis.legend(loc="best")

    output_path = figure_dir / "hgf_random_walk_latent_means_both_streams.png"
    save_figure(fig, output_path)


def plot_process_quantity(
    *,
    environment_df: pd.DataFrame,
    value_column: str,
    ylabel: str,
    title: str,
    output_filename: str,
    figure_dir: Path,
) -> None:
    """
    Plot process variance or process standard deviation for both streams.
    """

    fig, axis = plt.subplots(figsize=(12, 4))

    for stream in ["A", "B"]:
        stream_df = environment_df[environment_df["stream"] == stream]

        axis.plot(
            stream_df["trial_index"],
            stream_df[value_column],
            linewidth=2.0,
            label=f"{value_column} {stream}",
        )

    add_volatile_block_shading(axis, environment_df)

    axis.set_title(title)
    axis.set_xlabel("Trial index")
    axis.set_ylabel(ylabel)
    axis.legend(loc="best")

    output_path = figure_dir / output_filename
    save_figure(fig, output_path)


def plot_latent_innovations(
    *,
    environment_df: pd.DataFrame,
    figure_dir: Path,
) -> None:
    """
    Plot latent innovations for both streams.
    """

    fig, axis = plt.subplots(figsize=(12, 4))

    for stream in ["A", "B"]:
        stream_df = environment_df[environment_df["stream"] == stream]

        axis.plot(
            stream_df["trial_index"],
            stream_df["latent_innovation"],
            linewidth=0.8,
            label=f"latent innovation {stream}",
        )

    add_volatile_block_shading(axis, environment_df)

    axis.set_title("HGF-style random-walk environment — latent innovations")
    axis.set_xlabel("Trial index")
    axis.set_ylabel("Innovation")
    axis.legend(loc="best")

    output_path = figure_dir / "hgf_random_walk_latent_innovations.png"
    save_figure(fig, output_path)


def plot_observation_noise(
    *,
    environment_df: pd.DataFrame,
    figure_dir: Path,
) -> None:
    """
    Plot observation noise for both streams.

    This should look similar across stable and volatile blocks because
    observation noise is not the manipulation.
    """

    fig, axis = plt.subplots(figsize=(12, 4))

    for stream in ["A", "B"]:
        stream_df = environment_df[environment_df["stream"] == stream]

        axis.plot(
            stream_df["trial_index"],
            stream_df["observation_noise"],
            linewidth=0.8,
            label=f"observation noise {stream}",
        )

    add_volatile_block_shading(axis, environment_df)

    axis.set_title("HGF-style random-walk environment — observation noise")
    axis.set_xlabel("Trial index")
    axis.set_ylabel("Observation noise")
    axis.legend(loc="best")

    output_path = figure_dir / "hgf_random_walk_observation_noise.png"
    save_figure(fig, output_path)


def build_arg_parser() -> argparse.ArgumentParser:
    """
    Build command-line interface.
    """

    parser = argparse.ArgumentParser(
        description="Plot HGF-style random-walk environment diagnostics."
    )

    parser.add_argument(
        "--environment",
        type=str,
        default=str(DEFAULT_ENVIRONMENT_PATH),
        help="Path to environment_long.csv.",
    )

    parser.add_argument(
        "--output-dir",
        type=str,
        default=str(DEFAULT_FIGURE_DIR),
        help="Directory where figures should be saved.",
    )

    return parser


def main() -> None:
    """
    Load generated environment and save diagnostic plots.
    """

    parser = build_arg_parser()
    args = parser.parse_args()

    environment_df = load_environment(args.environment)
    figure_dir = Path(args.output_dir)
    figure_dir.mkdir(parents=True, exist_ok=True)

    plot_stream(
        environment_df=environment_df,
        stream="A",
        figure_dir=figure_dir,
    )

    plot_stream(
        environment_df=environment_df,
        stream="B",
        figure_dir=figure_dir,
    )

    plot_both_latent_means(
        environment_df=environment_df,
        figure_dir=figure_dir,
    )

    plot_process_quantity(
        environment_df=environment_df,
        value_column="process_variance",
        ylabel="Process variance Q",
        title="HGF-style random-walk environment — process variance",
        output_filename="hgf_random_walk_process_variance.png",
        figure_dir=figure_dir,
    )

    plot_process_quantity(
        environment_df=environment_df,
        value_column="process_sd",
        ylabel="Process SD sqrt(Q)",
        title="HGF-style random-walk environment — process standard deviation",
        output_filename="hgf_random_walk_process_sd.png",
        figure_dir=figure_dir,
    )

    plot_latent_innovations(
        environment_df=environment_df,
        figure_dir=figure_dir,
    )

    plot_observation_noise(
        environment_df=environment_df,
        figure_dir=figure_dir,
    )

    print("\nHGF-style random-walk environment plots generated successfully.")


if __name__ == "__main__":
    main()