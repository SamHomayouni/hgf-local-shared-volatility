# Coupling manipulation
# ---------------------------------------------------------------------

def set_volatility_edge_coupling(
    model,
    *,
    parent_idx: int,
    child_idx: int,
    coupling,
):
    """
    Set one existing volatility-coupling strength.

    The network topology has already been constructed.

    pyHGF stores coupling strengths on both sides of an edge:

        child:
            volatility_coupling_parents

        parent:
            volatility_coupling_children

    Both representations are therefore updated.

    Parameters
    ----------
    model:
        Existing pyHGF Network.

    parent_idx:
        Index of the volatility parent.

    child_idx:
        Index of the value child.

    coupling:
        JAX-compatible scalar coupling strength.

    Returns
    -------
    model:
        Network with the numerical coupling value replaced while
        preserving the existing graph structure.
    """

    coupling = (
        jnp.asarray(
            coupling
        )
        .squeeze()
    )

    # -------------------------------------------------------------
    # Locate this edge in the child's volatility-parent list.
    #
    # The edge structure is static Python information, so these
    # .index() operations do not depend on sampled parameters.
    # -------------------------------------------------------------

    volatility_parents = (
        model.edges[
            child_idx
        ].volatility_parents
    )

    if volatility_parents is None:
        raise ValueError(
            f"Child node {child_idx} has no volatility parents."
        )

    try:
        parent_position = (
            volatility_parents.index(
                parent_idx
            )
        )
    except ValueError as error:
        raise ValueError(
            f"Node {parent_idx} is not a volatility parent "
            f"of node {child_idx}."
        ) from error

    # -------------------------------------------------------------
    # Locate the same edge in the parent's child list.
    # -------------------------------------------------------------

    volatility_children = (
        model.edges[
            parent_idx
        ].volatility_children
    )

    if volatility_children is None:
        raise ValueError(
            f"Parent node {parent_idx} has no volatility children."
        )

    try:
        child_position = (
            volatility_children.index(
                child_idx
            )
        )
    except ValueError as error:
        raise ValueError(
            f"Node {child_idx} is not a volatility child "
            f"of node {parent_idx}."
        ) from error

    # -------------------------------------------------------------
    # Update CHILD-side representation.
    # -------------------------------------------------------------

    child_couplings = (
        model.attributes[
            child_idx
        ][
            "volatility_coupling_parents"
        ]
    )

    model.attributes[
        child_idx
    ][
        "volatility_coupling_parents"
    ] = (
        child_couplings
        .at[
            parent_position
        ]
        .set(
            coupling
        )
    )

    # -------------------------------------------------------------
    # Update PARENT-side representation.
    # -------------------------------------------------------------

    parent_couplings = (
        model.attributes[
            parent_idx
        ][
            "volatility_coupling_children"
        ]
    )

    model.attributes[
        parent_idx
    ][
        "volatility_coupling_children"
    ] = (
        parent_couplings
        .at[
            child_position
        ]
        .set(
            coupling
        )
    )

    return model


def set_local_volatility_coupling(
    model,
    volatility_coupling,
):
    """
    Apply one common sampled coupling strength to both local streams.

    Local-only edges:

        volatility A (4) -> value A (2)
        volatility B (5) -> value B (3)

    Both streams share the same fitted coupling parameter in this
    recovery test.
    """

    model = set_volatility_edge_coupling(
        model,
        parent_idx=VOLATILITY_A_NODE,
        child_idx=VALUE_A_NODE,
        coupling=volatility_coupling,
    )

    model = set_volatility_edge_coupling(
        model,
        parent_idx=VOLATILITY_B_NODE,
        child_idx=VALUE_B_NODE,
        coupling=volatility_coupling,
    )

    return model


# ---------------------------------------------------------------------
# JAX likelihood functions
# ---------------------------------------------------------------------

def create_likelihood_functions(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
):
    """
    Create total and trial-wise response likelihoods.

    Free perceptual parameter
    -------------------------
    volatility_coupling

    Free response parameter
    -----------------------
    log_response_sd

    Fixed perceptual parameters
    ---------------------------
    value_tonic_volatility      = -7.824
    volatility_tonic_volatility = -6.0
    """

    input_data_jax = jnp.asarray(
        input_data,
        dtype=jnp.float64,
    )

    responses_jax = jnp.asarray(
        responses,
        dtype=jnp.float64,
    )

    n_trials = int(
        len(responses)
    )

    include_mask = jnp.ones(
        n_trials,
        dtype=jnp.float64,
    )

    # Trial zero corresponds to the initial prior state.
    include_mask = (
        include_mask
        .at[0]
        .set(0.0)
    )

    # -------------------------------------------------------------
    # Total likelihood used by NUTS
    # -------------------------------------------------------------

    @wrap_jax
    def total_logp(
        value,
        log_response_sd,
        log_volatility_coupling,
    ):
        """
        Return the total response log likelihood.
        """

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        log_volatility_coupling = (
            jnp.asarray(
                log_volatility_coupling
            )
            .squeeze()
        )

        # Positive coupling.
        volatility_coupling = jnp.exp(
            log_volatility_coupling
        )

        # ---------------------------------------------------------
        # IMPORTANT:
        #
        # Construct the topology with an ordinary Python float.
        #
        # Do NOT pass volatility_coupling here because it is a JAX
        # tracer during PyMC/JAX inference.
        # ---------------------------------------------------------

        model = build_local_only_model(
            input_precision=(
                input_precision
            ),

            value_tonic_volatility=(
                FIXED_VALUE_TONIC_VOLATILITY
            ),

            volatility_tonic_volatility=(
                FIXED_VOLATILITY_TONIC_VOLATILITY
            ),

            # Static topology-construction value.
            volatility_coupling=1.0,

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        # ---------------------------------------------------------
        # Replace the static coupling values with the sampled JAX
        # value AFTER the graph has been built.
        # ---------------------------------------------------------

        model = set_local_volatility_coupling(
            model,
            volatility_coupling,
        )

        # ---------------------------------------------------------
        # Run the HGF.
        # ---------------------------------------------------------

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = (
                maybe_updated_model
            )

        # ---------------------------------------------------------
        # Build response-function inputs.
        #
        # value[:, 0] = participant prediction A
        # value[:, 1] = participant prediction B
        # column 3    = likelihood mask
        # ---------------------------------------------------------

        response_inputs = (
            jnp.column_stack(
                [
                    value[:, 0],
                    value[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,
                response_function_inputs=(
                    response_inputs
                ),
                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        # Completely remove trial zero.
        return -jnp.sum(
            surprise[1:]
        )

    # -------------------------------------------------------------
    # Pointwise likelihood used later for LOO
    # -------------------------------------------------------------

    @wrap_jax
    def pointwise_logp(
        log_response_sd,
        log_volatility_coupling,
    ):
        """
        Return one joint A+B log likelihood per included trial.
        """

        log_response_sd = (
            jnp.asarray(
                log_response_sd
            )
            .squeeze()
        )

        log_volatility_coupling = (
            jnp.asarray(
                log_volatility_coupling
            )
            .squeeze()
        )

        volatility_coupling = jnp.exp(
            log_volatility_coupling
        )

        # ---------------------------------------------------------
        # Again: static topology construction.
        # ---------------------------------------------------------

        model = build_local_only_model(
            input_precision=(
                input_precision
            ),

            value_tonic_volatility=(
                FIXED_VALUE_TONIC_VOLATILITY
            ),

            volatility_tonic_volatility=(
                FIXED_VOLATILITY_TONIC_VOLATILITY
            ),

            volatility_coupling=1.0,

            update_type=(
                update_type
            ),

            max_posterior_precision=(
                max_posterior_precision
            ),
        )

        # ---------------------------------------------------------
        # Insert sampled coupling after construction.
        # ---------------------------------------------------------

        model = set_local_volatility_coupling(
            model,
            volatility_coupling,
        )

        # ---------------------------------------------------------
        # Run HGF.
        # ---------------------------------------------------------

        maybe_updated_model = (
            model.input_data(
                input_data=(
                    input_data_jax
                )
            )
        )

        if maybe_updated_model is not None:
            model = (
                maybe_updated_model
            )

        response_inputs = (
            jnp.column_stack(
                [
                    responses_jax[:, 0],
                    responses_jax[:, 1],
                    include_mask,
                ]
            )
        )

        surprise = (
            two_stream_gaussian_prediction_surprise(
                model,
                response_function_inputs=(
                    response_inputs
                ),
                response_function_parameters=(
                    jnp.atleast_1d(
                        log_response_sd
                    )
                ),
            )
        )

        return -surprise[1:]

    return (
        total_logp,
        pointwise_logp,
    )


# ---------------------------------------------------------------------
# Bayesian fitting
# ---------------------------------------------------------------------

def run_fit(
    *,
    input_data: np.ndarray,
    responses: np.ndarray,
    input_precision: float,
    update_type: str,
    max_posterior_precision: float,
    draws: int,
    tune: int,
    chains: int,
    cores: int,
    target_accept: float,
    random_seed: int,
):
    """
    Estimate volatility coupling and response noise jointly.
    """

    (
        total_logp,
        pointwise_logp,
    ) = create_likelihood_functions(
        input_data=input_data,
        responses=responses,
        input_precision=input_precision,
        update_type=update_type,
        max_posterior_precision=(
            max_posterior_precision
        ),
    )

    with pm.Model() as model:

        # ---------------------------------------------------------
        # Response noise
        # ---------------------------------------------------------

        log_response_sd = pm.Normal(
            "log_response_sd",
            mu=np.log(
                0.20
            ),
            sigma=1.0,
        )

        response_sd = pm.Deterministic(
            "response_sd",
            pm.math.exp(
                log_response_sd
            ),
        )

        # ---------------------------------------------------------
        # Volatility coupling
        #
        # Positive coupling parameterized in log space:
        #
        #     log(kappa) ~ Normal(0, 1)
        #     kappa      = exp(log(kappa))
        #
        # Therefore the prior median is kappa = 1.
        # ---------------------------------------------------------

        log_volatility_coupling = pm.Normal(
            "log_volatility_coupling",
            mu=0.0,
            sigma=1.0,
        )

        volatility_coupling = pm.Deterministic(
            "volatility_coupling",
            pm.math.exp(
                log_volatility_coupling
            ),
        )

        # ---------------------------------------------------------
        # Response likelihood
        # ---------------------------------------------------------

        pm.CustomDist(
            "response_likelihood",
            log_response_sd,
            log_volatility_coupling,
            logp=total_logp,
            observed=responses,
        )

        # ---------------------------------------------------------
        # Pointwise likelihood for later PSIS-LOO.
        # ---------------------------------------------------------

        pm.Deterministic(
            "pointwise_loglikelihood",
            pointwise_logp(
                log_response_sd,
                log_volatility_coupling,
            ),
        )

        idata = pm.sample(
            draws=draws,
            tune=tune,
            chains=chains,
            cores=cores,
            backend="jax",
            target_accept=(
                target_accept
            ),
            random_seed=(
                random_seed
            ),
            return_inferencedata=True,
        )

    # -------------------------------------------------------------
    # Put trial-wise likelihood into the ArviZ log_likelihood group.
    # -------------------------------------------------------------

    idata["log_likelihood"] = (
        idata.posterior[
            "pointwise_loglikelihood"
        ]
        .to_dataset(
            name="log_likelihood"
        )
    )

    return (
        model,
        idata,
    )


# ---------------------------------------------------------------------
# Posterior utilities
