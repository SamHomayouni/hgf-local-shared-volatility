# ---------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------

def main() -> None:
    """
    Run the volatility-coupling recovery test.
    """

    args = (
        build_arg_parser()
        .parse_args()
    )

    environment_dir = Path(
        args.environment_dir
    )

    if args.output_dir is None:

        output_dir = (
            environment_dir
            / "model_recovery"
            / "bayesian_parameter_smoke_test"
            / "volatility_coupling"
        )

    else:

        output_dir = Path(
            args.output_dir
        )

    # -------------------------------------------------------------
    # Terminal header
    # -------------------------------------------------------------

    print(
        "\n========================================"
    )

    print(
        "Bayesian volatility-coupling recovery"
    )

    print(
        "========================================"
    )

    print(
        f"Environment: "
        f"{environment_dir}"
    )

    print(
        "Generating model: local_only"
    )

    print(
        "Candidate model: local_only"
    )

    print(
        f"Fixed value tonic volatility: "
        f"{FIXED_VALUE_TONIC_VOLATILITY}"
    )

    print(
        f"Fixed volatility tonic volatility: "
        f"{FIXED_VOLATILITY_TONIC_VOLATILITY}"
    )

    print(
        f"True volatility coupling: "
        f"{TRUE_VOLATILITY_COUPLING}"
    )

    # -------------------------------------------------------------
    # Load data
    # -------------------------------------------------------------

    input_data = load_model_input(
        environment_dir
    )

    (
        responses,
        response_metadata,
    ) = load_synthetic_responses(
        environment_dir=environment_dir,
    )

    if len(input_data) != len(responses):
        raise ValueError(
            "Number of input trials and response trials "
            "does not match:\n"
            f"    input trials:    {len(input_data)}\n"
            f"    response trials: {len(responses)}"
        )

    # -------------------------------------------------------------
    # True response noise
    # -------------------------------------------------------------

    true_response_sd_A = float(
        response_metadata[
            "response_sd_A"
        ]
    )

    true_response_sd_B = float(
        response_metadata[
            "response_sd_B"
        ]
    )

    if not np.isclose(
        true_response_sd_A,
        true_response_sd_B,
    ):
        raise ValueError(
            "This recovery test assumes one shared "
            "response-noise parameter, but the generating "
            "response SD differs between streams."
        )

    true_response_sd = (
        true_response_sd_A
    )

    print(
        f"True response SD: "
        f"{true_response_sd}"
    )

    print(
        f"Trials total: "
        f"{len(responses)}"
    )

    print(
        f"Trials in likelihood: "
        f"{len(responses) - 1}"
    )

    print(
        f"Chains: "
        f"{args.chains}"
    )

    print(
        f"Draws per chain: "
        f"{args.draws}"
    )

    print(
        f"Tuning steps per chain: "
        f"{args.tune}"
    )

    print(
        f"Target accept: "
        f"{args.target_accept}"
    )

    # -------------------------------------------------------------
    # Bayesian fitting
    # -------------------------------------------------------------

    _, idata = run_fit(
        input_data=input_data,
        responses=responses,

        input_precision=(
            args.input_precision
        ),

        update_type=(
            args.update_type
        ),

        max_posterior_precision=(
            args.max_posterior_precision
        ),

        draws=(
            args.draws
        ),

        tune=(
            args.tune
        ),

        chains=(
            args.chains
        ),

        cores=(
            args.cores
        ),

        target_accept=(
            args.target_accept
        ),

        random_seed=(
            args.random_seed
        ),
    )

    # -------------------------------------------------------------
    # Recovery diagnostics
    # -------------------------------------------------------------

    (
        posterior_summary,
        diagnostics,
    ) = summarize_recovery(
        idata=idata,
        true_response_sd=(
            true_response_sd
        ),
    )

    print(
        "\nPosterior summary"
    )

    print(
        posterior_summary.to_string()
    )

    print(
        "\nRecovery diagnostics"
    )

    for key, value in (
        diagnostics.items()
    ):
        print(
            f"    {key}: {value}"
        )

    # -------------------------------------------------------------
    # Metadata
    # -------------------------------------------------------------

    metadata = {

        "environment_dir": str(
            environment_dir
        ),

        "generating_model": (
            "local_only"
        ),

        "candidate_model": (
            "local_only"
        ),

        "free_parameters": [
            "log_volatility_coupling",
            "log_response_sd",
        ],

        "derived_parameters": [
            "volatility_coupling",
            "response_sd",
        ],

        "fixed_parameters": {

            "value_tonic_volatility": float(
                FIXED_VALUE_TONIC_VOLATILITY
            ),

            "volatility_tonic_volatility": float(
                FIXED_VOLATILITY_TONIC_VOLATILITY
            ),
        },

        "true_parameters": {

            "volatility_coupling": float(
                TRUE_VOLATILITY_COUPLING
            ),

            "response_sd": float(
                true_response_sd
            ),
        },

        "priors": {

            "log_volatility_coupling": {

                "distribution": (
                    "Normal"
                ),

                "mu": 0.0,

                "sigma": 1.0,

                "transformation": (
                    "volatility_coupling = "
                    "exp(log_volatility_coupling)"
                ),
            },

            "log_response_sd": {

                "distribution": (
                    "Normal"
                ),

                "mu": float(
                    np.log(
                        0.20
                    )
                ),

                "sigma": 1.0,

                "transformation": (
                    "response_sd = "
                    "exp(log_response_sd)"
                ),
            },
        },

        "sampling": {

            "backend": (
                "jax"
            ),

            "sampler": (
                "NUTS"
            ),

            "draws": int(
                args.draws
            ),

            "tune": int(
                args.tune
            ),

            "chains": int(
                args.chains
            ),

            "cores": int(
                args.cores
            ),

            "target_accept": float(
                args.target_accept
            ),

            "random_seed": int(
                args.random_seed
            ),
        },

        "first_trial_excluded": True,

        "implementation_note": (
            "The pyHGF network topology is constructed using "
            "static volatility_coupling=1.0. The sampled JAX "
            "coupling is then inserted into both parent-side and "
            "child-side coupling arrays before input_data() is run."
        ),
    }

    # -------------------------------------------------------------
    # Save
    # -------------------------------------------------------------

    save_outputs(
        output_dir=(
            output_dir
        ),

        idata=(
            idata
        ),

        posterior_summary=(
            posterior_summary
        ),

        diagnostics=(
            diagnostics
        ),

        metadata=(
            metadata
        ),
    )

    print(
        "\nFinished volatility-coupling recovery test."
    )


if __name__ == "__main__":
    main()