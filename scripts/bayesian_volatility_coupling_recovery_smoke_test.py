def summarize_recovery(
    *,
    idata,
    true_response_sd: float,
) -> tuple[
    pd.DataFrame,
    dict,
]:
    """
    Summarize coupling recovery and sampler diagnostics.
    """

    posterior_summary = az.summary(
        idata,
        var_names=[
            "log_volatility_coupling",
            "volatility_coupling",
            "log_response_sd",
            "response_sd",
        ],
        round_to=4,
    )

    # -------------------------------------------------------------
    # Extract posterior samples
    # -------------------------------------------------------------

    coupling_samples = flatten_samples(
        idata,
        "volatility_coupling",
    )

    log_coupling_samples = flatten_samples(
        idata,
        "log_volatility_coupling",
    )

    response_sd_samples = flatten_samples(
        idata,
        "response_sd",
    )

    # -------------------------------------------------------------
    # HDIs
    # -------------------------------------------------------------

    coupling_hdi = az.hdi(
        coupling_samples,
        hdi_prob=0.94,
    )

    response_sd_hdi = az.hdi(
        response_sd_samples,
        hdi_prob=0.94,
    )

    # -------------------------------------------------------------
    # Posterior correlations
    # -------------------------------------------------------------

    coupling_response_correlation = float(
        np.corrcoef(
            coupling_samples,
            response_sd_samples,
        )[0, 1]
    )

    log_coupling_response_correlation = float(
        np.corrcoef(
            log_coupling_samples,
            response_sd_samples,
        )[0, 1]
    )

    # -------------------------------------------------------------
    # Divergences
    # -------------------------------------------------------------

    n_divergences = int(
        idata.sample_stats[
            "diverging"
        ]
        .sum()
        .values
    )

    # -------------------------------------------------------------
    # Diagnostic dictionary
    # -------------------------------------------------------------

    diagnostics = {

        "fixed_value_tonic_volatility": float(
            FIXED_VALUE_TONIC_VOLATILITY
        ),

        "fixed_volatility_tonic_volatility": float(
            FIXED_VOLATILITY_TONIC_VOLATILITY
        ),

        # ---------------------------------------------------------
        # Volatility coupling
        # ---------------------------------------------------------

        "true_volatility_coupling": float(
            TRUE_VOLATILITY_COUPLING
        ),

        "posterior_mean_volatility_coupling": float(
            np.mean(
                coupling_samples
            )
        ),

        "posterior_median_volatility_coupling": float(
            np.median(
                coupling_samples
            )
        ),

        "volatility_coupling_hdi_94_lower": float(
            coupling_hdi[0]
        ),

        "volatility_coupling_hdi_94_upper": float(
            coupling_hdi[1]
        ),

        "true_volatility_coupling_inside_94_hdi": bool(
            coupling_hdi[0]
            <= TRUE_VOLATILITY_COUPLING
            <= coupling_hdi[1]
        ),

        # ---------------------------------------------------------
        # Response noise
        # ---------------------------------------------------------

        "true_response_sd": float(
            true_response_sd
        ),

        "posterior_mean_response_sd": float(
            np.mean(
                response_sd_samples
            )
        ),

        "posterior_median_response_sd": float(
            np.median(
                response_sd_samples
            )
        ),

        "response_sd_hdi_94_lower": float(
            response_sd_hdi[0]
        ),

        "response_sd_hdi_94_upper": float(
            response_sd_hdi[1]
        ),

        "true_response_sd_inside_94_hdi": bool(
            response_sd_hdi[0]
            <= true_response_sd
            <= response_sd_hdi[1]
        ),

        # ---------------------------------------------------------
        # Posterior dependence
        # ---------------------------------------------------------

        "posterior_correlation_coupling_vs_response_sd": (
            coupling_response_correlation
        ),

        "posterior_correlation_log_coupling_vs_response_sd": (
            log_coupling_response_correlation
        ),

        "absolute_correlation_coupling_vs_response_sd": float(
            abs(
                coupling_response_correlation
            )
        ),

        # ---------------------------------------------------------
        # Sampling
        # ---------------------------------------------------------

        "n_divergences": int(
            n_divergences
        ),
    }

    return (
        posterior_summary,
        diagnostics,
    )


# ---------------------------------------------------------------------
