def flatten_samples(
    idata,
    variable_name: str,
) -> np.ndarray:
    """
    Flatten chain and draw dimensions into one vector.
    """

    return (
        idata.posterior[
            variable_name
        ]
        .values
        .reshape(-1)
    )


