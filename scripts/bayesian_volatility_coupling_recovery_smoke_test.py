"""
Bayesian recovery smoke test for local-only volatility coupling.

Free parameters
---------------
1. volatility_coupling
2. shared response noise SD

Fixed perceptual parameters
---------------------------
value_tonic_volatility      = -7.824
volatility_tonic_volatility = -6.0

Known generating values
-----------------------
volatility_coupling = 1.0
response_sd         = 0.10

Purpose
-------
Test whether the strength of volatility coupling can be recovered from
synthetic continuous prediction behavior when the tonic-volatility
parameters are fixed.

Important implementation detail
-------------------------------
The sampled volatility coupling must NOT be passed directly into
build_local_only_model() while the pyHGF network is being constructed.

pyHGF's add_edges() function expects ordinary Python coupling values
during topology construction. A JAX tracer therefore cannot be used
there directly.

Instead:

    1. Build the network with a static Python coupling value of 1.0.
    2. Keep the network topology fixed.
    3. Replace the coupling-strength arrays stored in model.attributes
       with the sampled JAX coupling value.
    4. Run the HGF.

This preserves differentiability while avoiding the add_edges()
AssertionError.

Positive coupling is parameterized in log space:

    log_volatility_coupling ~ Normal(0, 1)
    volatility_coupling = exp(log_volatility_coupling)

The script also estimates shared response noise and stores pointwise
log likelihoods for the later LOO model-comparison pipeline.
"""

