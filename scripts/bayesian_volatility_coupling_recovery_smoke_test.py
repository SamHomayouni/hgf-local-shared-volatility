def load_model_input(
    environment_dir: Path,
) -> np.ndarray:
    """
    Load the two-stream observations used by the HGF.
    """

    input_path = (
        environment_dir
        / "model_runs"
        / "model_input_data.npy"
    )

    if not input_path.exists():
        raise FileNotFoundError(
            f"Could not find model input data: {input_path}"
        )

    input_data = np.load(
        input_path
    )

    if input_data.ndim != 2:
        raise ValueError(
            "Expected a 2D model-input matrix, "
            f"got shape {input_data.shape}."
        )

    if input_data.shape[1] != 2:
        raise ValueError(
            "Expected exactly two observation streams, "
            f"got shape {input_data.shape}."
        )

    if not np.isfinite(input_data).all():
        raise ValueError(
            "Model input contains non-finite values."
        )

    return input_data.astype(
        float
    )


def load_synthetic_responses(
    *,
    environment_dir: Path,
) -> tuple[np.ndarray, dict]:
    """
    Load responses generated by the local-only perceptual model.
    """

    response_dir = (
        environment_dir
        / "synthetic_responses"
        / "local_only"
    )

    response_path = (
        response_dir
        / "synthetic_continuous_predictions.csv"
    )

    metadata_path = (
        response_dir
        / "response_model_metadata.json"
    )

    if not response_path.exists():
        raise FileNotFoundError(
            f"Could not find responses: {response_path}"
        )

    if not metadata_path.exists():
        raise FileNotFoundError(
            f"Could not find response metadata: {metadata_path}"
        )

    response_df = pd.read_csv(
        response_path
    )

    with metadata_path.open(
        "r",
        encoding="utf-8",
    ) as file:
        metadata = json.load(
            file
        )

    required_columns = {
        "participant_prediction_A",
        "participant_prediction_B",
    }

    missing_columns = (
        required_columns
        - set(response_df.columns)
    )

    if missing_columns:
        raise ValueError(
            "Synthetic response file is missing columns: "
            f"{sorted(missing_columns)}"
        )

    generating_model = metadata.get(
        "generating_perceptual_model"
    )

    if generating_model != "local_only":
        raise ValueError(
            "This recovery test expects responses generated "
            "by local_only, but metadata reports "
            f"{generating_model!r}."
        )

    responses = response_df[
        [
            "participant_prediction_A",
            "participant_prediction_B",
        ]
    ].to_numpy(
        dtype=float
    )

    if not np.isfinite(responses).all():
        raise ValueError(
            "Synthetic responses contain non-finite values."
        )

    return (
        responses,
        metadata,
    )


