"""
Plot the generated two-stream environment.

This script reads the environment generated by:

    src/environments/two_stream_changepoint.py

and saves diagnostic plots showing:
    - observed inputs
    - latent means
    - change points
    - A-volatile blocks
"""

from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd


DATA_DIR = Path("outputs/data")
FIGURE_DIR = Path("outputs/figures")

ENVIRONMENT_PATH = DATA_DIR / "environment_long.csv"


def add_volatile_block_shading(axis) -> None:
    """
    Shade the blocks where stream A is objectively volatile.

    With zero-based indexing:
        V1 = indices 200 to 399
        V2 = indices 600 to 799

    matplotlib axvspan uses continuous x coordinates, so:
        axvspan(200, 400)
        axvspan(600, 800)
    """
    axis.axvspan(200, 400, alpha=0.15, label="A volatile block")
    axis.axvspan(600, 800, alpha=0.15)


def plot_stream(environment_df: pd.DataFrame, stream: str) -> None:
    """
    Plot one stream's latent mean, observations, and change points.
    """
    stream_df = environment_df[environment_df["stream"] == stream].copy()

    fig, axis = plt.subplots(figsize=(12, 4))

    axis.plot(
        stream_df["trial_index"],
        stream_df["observation"],
        linewidth=0.7,
        label=f"observation {stream}",
    )

    axis.plot(
        stream_df["trial_index"],
        stream_df["latent_mean"],
        linewidth=2.0,
        label=f"latent mean {stream}",
    )

    changepoint_df = stream_df[stream_df["changepoint"]]

    axis.scatter(
        changepoint_df["trial_index"],
        changepoint_df["latent_mean"],
        s=35,
        marker="x",
        label="change point",
    )

    add_volatile_block_shading(axis)

    axis.set_title(f"Generated environment — stream {stream}")
    axis.set_xlabel("Trial index")
    axis.set_ylabel("Value")
    axis.legend(loc="best")

    fig.tight_layout()

    output_path = FIGURE_DIR / f"environment_stream_{stream}.png"
    fig.savefig(output_path, dpi=150)
    plt.close(fig)

    print(f"Saved: {output_path}")


def plot_both_streams(environment_df: pd.DataFrame) -> None:
    """
    Plot latent means of both streams together.

    This helps check whether A changes more than B during the volatile blocks.
    """
    fig, axis = plt.subplots(figsize=(12, 4))

    for stream in ["A", "B"]:
        stream_df = environment_df[environment_df["stream"] == stream]

        axis.plot(
            stream_df["trial_index"],
            stream_df["latent_mean"],
            linewidth=2.0,
            label=f"latent mean {stream}",
        )

    add_volatile_block_shading(axis)

    axis.set_title("Generated environment — latent means of both streams")
    axis.set_xlabel("Trial index")
    axis.set_ylabel("Latent mean")
    axis.legend(loc="best")

    fig.tight_layout()

    output_path = FIGURE_DIR / "environment_latent_means_both_streams.png"
    fig.savefig(output_path, dpi=150)
    plt.close(fig)

    print(f"Saved: {output_path}")


def main() -> None:
    """
    Load generated environment and save diagnostic plots.
    """
    if not ENVIRONMENT_PATH.exists():
        raise FileNotFoundError(
            f"Could not find {ENVIRONMENT_PATH}. "
            "Run two_stream_changepoint.py first."
        )

    FIGURE_DIR.mkdir(parents=True, exist_ok=True)

    environment_df = pd.read_csv(ENVIRONMENT_PATH)

    plot_stream(environment_df, stream="A")
    plot_stream(environment_df, stream="B")
    plot_both_streams(environment_df)

    print("\nEnvironment plots generated successfully.")


if __name__ == "__main__":
    main()